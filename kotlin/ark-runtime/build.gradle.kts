// §5 The Unicode tables trim, lower and is_alnum consult, pinned to the
// version the spec pins: generated from `rust/ark/src/unicode_tables.rs`,
// which is gen-unicode's output from the Unicode Character Database, so the
// two runtimes read one copy and none is written by hand. Each table
// becomes one string of hex tokens parsed once — an array literal is
// bytecode in `<clinit>`, which the JVM caps at 64 KB.
val unicodeSource = rootProject.file("../rust/ark/src/unicode_tables.rs")
val unicodeOut = layout.buildDirectory.dir("generated/unicode")
val unicodeTables by tasks.registering {
    description = "Writes UnicodeTables.kt from rust/ark/src/unicode_tables.rs."
    inputs.file(unicodeSource)
    outputs.dir(unicodeOut)
    doLast {
        val text = unicodeSource.readText()
        val version = Regex("pub const UNICODE_VERSION: &str = \"([^\"]+)\";").find(text)?.groupValues?.get(1)
            ?: throw GradleException("unicode_tables.rs: no UNICODE_VERSION")
        fun table(name: String): String {
            val m = Regex("static $name: \\[\\(u32, u32\\); (\\d+)\\] = \\[(.*?)\\];", RegexOption.DOT_MATCHES_ALL).find(text)
                ?: throw GradleException("unicode_tables.rs: no table $name")
            val pairs = Regex("\\(0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\\)").findAll(m.groupValues[2]).toList()
            if (pairs.size != m.groupValues[1].toInt()) throw GradleException("unicode_tables.rs: $name has ${pairs.size} pairs, says ${m.groupValues[1]}")
            val tokens = pairs.flatMap { listOf(it.groupValues[1], it.groupValues[2]) }
            return tokens.chunked(16).joinToString(" +\n            ") { "\"" + it.joinToString(",") + "," + "\"" }
        }
        val out = unicodeOut.get().file("dev/arkdb/UnicodeTables.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// GENERATED by ark-runtime/build.gradle.kts from rust/ark/src/unicode_tables.rs,
            |// which gen-unicode writes from the Unicode $version Character Database. Do not edit.
            |package dev.arkdb
            |
            |/** §5 Unicode character properties, pinned to UCD $version (`rust/ark/src/unicode_tables.rs`). */
            |public object UnicodeTables {
            |    /** The Unicode version every table here was generated from. */
            |    public const val VERSION: String = "$version"
            |
            |    /** Property `White_Space` (PropList.txt). */
            |    public fun isWhiteSpace(cp: Int): Boolean = inRanges(WHITE_SPACE, cp)
            |
            |    /** `Alphabetic`, or a general category of `Nd`, `Nl` or `No`: Rust's `char::is_alphanumeric`, pinned. */
            |    public fun isAlphanumeric(cp: Int): Boolean = inRanges(ALPHANUMERIC, cp)
            |
            |    /** The simple lowercase mapping (UnicodeData.txt field 13); identity where there is none. */
            |    public fun toLowerSimple(cp: Int): Int {
            |        val i = floorIndex(LOWER, cp)
            |        return if (i >= 0 && LOWER[2 * i] == cp) LOWER[2 * i + 1] else cp
            |    }
            |
            |    private fun inRanges(table: IntArray, n: Int): Boolean {
            |        val i = floorIndex(table, n)
            |        return i >= 0 && n <= table[2 * i + 1]
            |    }
            |
            |    // The index of the last pair whose first component is at most `n`, or -1.
            |    private fun floorIndex(table: IntArray, n: Int): Int {
            |        var lo = 0
            |        var hi = table.size / 2 - 1
            |        if (hi < 0 || table[0] > n) return -1
            |        while (lo < hi) {
            |            val m = (lo + hi + 1) / 2
            |            if (table[2 * m] <= n) lo = m else hi = m - 1
            |        }
            |        return lo
            |    }
            |
            |    private fun parse(s: String): IntArray = s.trimEnd(',').split(',').map { it.toInt(16) }.toIntArray()
            |
            |    private val WHITE_SPACE: IntArray = parse(
            |        ${table("WHITE_SPACE")}
            |    )
            |
            |    private val ALPHANUMERIC: IntArray = parse(
            |        ${table("ALPHANUMERIC")}
            |    )
            |
            |    private val LOWER: IntArray = parse(
            |        ${table("LOWER")}
            |    )
            |}
            |""".trimMargin()
        )
    }
}
sourceSets["main"].kotlin.srcDir(unicodeTables)

// The conformance runner is a plain `main` rather than a JUnit suite, so
// that it needs no test framework on the classpath: it reads
// spec/vectors/MANIFEST.json, runs every vector of the kinds it claims,
// prints what it ran and skipped by name, and exits non-zero on a failure
// or on a claimed kind with nothing run.
val conformance by tasks.registering(JavaExec::class) {
    group = "verification"
    description = "Runs spec/vectors through the runtime (spec/RUNNERS.md)."
    dependsOn(tasks.named("testClasses"))
    classpath = sourceSets["test"].runtimeClasspath
    mainClass.set("dev.arkdb.conformance.Conformance")
    jvmArgs("-Dstdout.encoding=UTF-8", "-Dstderr.encoding=UTF-8")
    val vectors = providers.gradleProperty("arkVectors")
        .orElse(rootProject.file("../spec/vectors").absolutePath)
    args(vectors.get())
}

// R9's kept numbers held, past what the views vectors reach, to a fresh
// hydrate and to a fold's answer, over seeded random batches.
val keptNumbers by tasks.registering(JavaExec::class) {
    group = "verification"
    description = "Holds kept numbers three levels deep to a fresh read."
    dependsOn(tasks.named("testClasses"))
    classpath = sourceSets["test"].runtimeClasspath
    mainClass.set("dev.arkdb.conformance.KeptNumbers")
    val vectors = providers.gradleProperty("arkVectors")
        .orElse(rootProject.file("../spec/vectors").absolutePath)
    args(vectors.get())
}

tasks.named("check") {
    dependsOn(conformance, keptNumbers)
