//! `arkc gen kotlin|swift`: a module's type section and live states printed
//! as Kotlin and Swift types (`docs/plan-live.md`), so that an app reads a
//! state — harken's `listening`, the demo's `room` — as a typed value rather
//! than walking a `Value` by hand.
//!
//! Every record of the type section becomes a record type (a Kotlin data
//! class, a Swift struct), every sum a closed one (a sealed class, an enum),
//! and each is read from the runtime's `Value` (`of`, `init(_:)`) and written
//! back as one (`toValue`, `value`), field for field, so that reading a value
//! and writing it again is the value — what the runtimes' round-trip tests
//! hold the printed demo to. A record or a sum written in place, with no name
//! of its own, is printed beside the type it is in, named by where it is
//! (`room.devices` is `RoomDevices`). `LiveStates` names every live state and
//! reads each as its type.
//!
//! The type each type of the section is printed as:
//!
//! | type | Kotlin | Swift |
//! |---|---|---|
//! | `Bool`, `Int`, `Text`, `Bytes`, `Id` | `Boolean`, `Long`, `String`, `ByteArray`, `Id` | `Bool`, `Int64`, `String`, `[UInt8]`, `Id` |
//! | `Enum` | `String` | `String` |
//! | `Option t` | `T?` | `T?` |
//! | `List t`, `NonEmpty t` | `List<T>` | `[T]` |
//! | `PerDevice t` | `Map<String, T>` by device id | `[String: T]` |
//! | `Ephemeral t` | `T`, said in its comment | `T`, said in its comment |
//! | `Named n`, a record, a sum | the printed type | the printed type |
//!
//! Field and variant names are camel-cased (`can_play` is `canPlay`) and
//! type names Pascal-cased (`room` is `Room`); what goes on the wire is the
//! module's name, always.

use std::collections::BTreeMap;

use ark::ir::Module;
use ark::schema::Ty;

/// The header every printed file starts with, after its comment marker.
const HEADER: [&str; 4] = [
    "GENERATED by `arkc gen` from a module's type section and live states",
    "(docs/plan-live.md): each record a record type, each sum a closed one,",
    "each read from the runtime's Value and written back as one. Edit the",
    "domain and print it again; never this file.",
];

// One type to print: its name, what it is, and what to say of it.
struct Decl {
    name: String,
    ty: Ty,
    about: String,
}

// The types to print, in the order they are met: the type section's in its
// order, each followed by the records and sums written in place inside it.
struct Decls {
    all: Vec<Decl>,
    types: BTreeMap<String, Ty>,
}

impl Decls {
    fn of(m: &Module) -> Decls {
        let mut d = Decls {
            all: vec![],
            types: m.type_map(),
        };
        for (n, t) in &m.types {
            d.all.push(Decl {
                name: pascal(n),
                ty: t.clone(),
                about: format!("The type `{n}` of the module's type section"),
            });
        }
        for s in &m.states {
            if matches!(s.ty, Ty::Struct(_) | Ty::Sum(_)) {
                let name = d.fresh(pascal(&s.name));
                d.all.push(Decl {
                    name,
                    ty: s.ty.clone(),
                    about: format!("The type of the live state `{}`", s.name),
                });
            }
        }
        d
    }

    // A name no printed type has yet.
    fn fresh(&self, want: String) -> String {
        let taken = |n: &str| self.all.iter().any(|d| d.name == n);
        if !taken(&want) {
            return want;
        }
        let mut k = 2;
        while taken(&format!("{want}{k}")) {
            k += 1;
        }
        format!("{want}{k}")
    }

    // The name a record or sum written in place is printed under, queued to
    // be printed after the one it is in.
    fn inline(&mut self, hint: &str, t: &Ty, about: String) -> String {
        if let Some(d) = self.all.iter().find(|d| d.ty == *t && d.name.starts_with(hint)) {
            return d.name.clone();
        }
        let name = self.fresh(hint.to_string());
        self.all.push(Decl {
            name: name.clone(),
            ty: t.clone(),
            about,
        });
        name
    }

    // A state's type, as the type it is printed as.
    fn state_ty(&self, s: &ark::ir::State) -> Ty {
        match &s.ty {
            Ty::Struct(_) | Ty::Sum(_) => {
                let d = self.all.iter().find(|d| d.ty == s.ty && d.about.ends_with(&format!("`{}`", s.name)));
                Ty::Named(d.map_or_else(|| pascal(&s.name), |d| d.name.clone()))
            }
            other => other.clone(),
        }
    }
}

// What is said of a record or a sum with no name of its own.
fn written_in_place() -> String {
    "Written in place in a type above, and named for where it is".into()
}

// What a named type is, through its declaration: a record or a sum is printed
// under its own name, anything else is the type it stands for.
fn declared<'a>(types: &'a BTreeMap<String, Ty>, t: &'a Ty) -> &'a Ty {
    match t {
        Ty::Named(n) => match types.get(n) {
            Some(Ty::Struct(_) | Ty::Sum(_)) => t,
            Some(d) => declared(types, d),
            None => t,
        },
        other => other,
    }
}

// Whether `t` has an id anywhere in it, which the Kotlin imports.
fn has_id(t: &Ty) -> bool {
    match t {
        Ty::Id(_) => true,
        Ty::Option(x) | Ty::List(x) | Ty::NonEmpty(x) | Ty::PerDevice(x) | Ty::Ephemeral(x) => has_id(x),
        Ty::Struct(fs) => fs.values().any(has_id),
        Ty::Sum(vs) => vs.values().any(|fs| fs.values().any(has_id)),
        _ => false,
    }
}

/// `pascal_case`: `track_info` is `TrackInfo`.
fn pascal(s: &str) -> String {
    let out: String = s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut cs = w.chars();
            match cs.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + cs.as_str(),
                None => String::new(),
            }
        })
        .collect();
    match out.chars().next() {
        Some(c) if c.is_ascii_alphabetic() => out,
        _ => format!("T{out}"),
    }
}

/// `camel_case`: `can_play` is `canPlay`.
fn camel(s: &str) -> String {
    let p = pascal(s);
    let mut cs = p.chars();
    match cs.next() {
        Some(f) => f.to_ascii_lowercase().to_string() + cs.as_str(),
        None => p,
    }
}

/// `UPPER_SNAKE`: `listening` is `LISTENING`.
fn upper(s: &str) -> String {
    let out: String = s
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' })
        .collect();
    match out.chars().next() {
        Some(c) if c.is_ascii_alphabetic() => out,
        _ => format!("S_{out}"),
    }
}

/// A string literal, in either language: `"`, `\` and `$` escaped.
fn lit(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '$' => o.push_str("\\$"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

