const KOTLIN_KEYWORDS: &str = "as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while";

fn kt_name(s: &str) -> String {
    let c = camel(s);
    if KOTLIN_KEYWORDS.split(' ').any(|k| k == c) {
        format!("`{c}`")
    } else {
        c
    }
}

/// `arkc gen kotlin M PACKAGE`: the module's types and live states as Kotlin,
/// in `package`, over the runtime's `dev.arkdb.Value`.
pub fn kotlin(m: &Module, package: &str) -> String {
    let mut d = Decls::of(m);
    let mut o = String::new();
    for l in HEADER {
        o.push_str(&format!("// {l}\n"));
    }
    let id = m.types.iter().map(|(_, t)| t).chain(m.states.iter().map(|s| &s.ty)).any(has_id);
    o.push_str(&format!(
        "package {package}\n\n{}import dev.arkdb.Value\n",
        if id { "import dev.arkdb.Id\n" } else { "" }
    ));
    let mut i = 0;
    while i < d.all.len() {
        let (name, ty, about) = (d.all[i].name.clone(), d.all[i].ty.clone(), d.all[i].about.clone());
        o.push('\n');
        match &ty {
            Ty::Struct(fs) => o.push_str(&kt_record(&mut d, &name, fs, &about)),
            Ty::Sum(vs) => o.push_str(&kt_sum(&mut d, &name, vs, &about)),
            other => o.push_str(&format!("/** {about}. */\npublic typealias {name} = {}\n", kt_ty(&mut d, &name, other))),
        }
        i += 1;
    }
    o.push_str("\n/** The module's live states, by name, each read as its type. */\npublic object LiveStates {\n");
    for (k, s) in m.states.iter().enumerate() {
        if k > 0 {
            o.push('\n');
        }
        let t = d.state_ty(s);
        o.push_str(&format!(
            "    /** The live state `{n}`. */\n    public const val {u}: String = {l}\n\n    /** The live state `{n}`, read as its type. */\n    public fun {f}(v: Value): {ty} = {dec}\n",
            n = s.name,
            u = upper(&s.name),
            l = lit(&s.name),
            f = kt_name(&s.name),
            ty = kt_ty(&mut d, &pascal(&s.name), &t),
            dec = kt_dec(&mut d, &pascal(&s.name), &t, "v", 0),
        ));
    }
    o.push_str("}\n");
    o
}

fn kt_record(d: &mut Decls, name: &str, fs: &BTreeMap<String, Ty>, about: &str) -> String {
    let mut o = format!("/** {about}: a record. */\n");
    if fs.is_empty() {
        o.push_str(&format!(
            "public data object {name} {{\n    /** As the runtime's value. */\n    public fun toValue(): Value = Value.record()\n\n    /** From the runtime's value. */\n    public fun of(v: Value): {name} = this\n}}\n"
        ));
        return o;
    }
    o.push_str(&format!("public data class {name}(\n"));
    for (f, t) in fs {
        if matches!(t, Ty::Ephemeral(_)) {
            o.push_str("    /** Ephemeral: each device writes its own slot, never ordered, never kept. */\n");
        }
        o.push_str(&format!(
            "    public val {}: {},\n",
            kt_name(f),
            kt_ty(d, &format!("{name}{}", pascal(f)), t)
        ));
    }
    o.push_str(") {\n    /** As the runtime's value. */\n    public fun toValue(): Value =\n        Value.record(\n");
    for (f, t) in fs {
        o.push_str(&format!(
            "            {} to {},\n",
            lit(f),
            kt_enc(d, &format!("{name}{}", pascal(f)), t, &kt_name(f), 0)
        ));
    }
    o.push_str(&format!(
        "        )\n\n    public companion object {{\n        /** From the runtime's value. */\n        public fun of(v: Value): {name} =\n            {name}(\n"
    ));
    for (f, t) in fs {
        o.push_str(&format!(
            "                {},\n",
            kt_dec(d, &format!("{name}{}", pascal(f)), t, &format!("v.field({})", lit(f)), 0)
        ));
    }
    o.push_str("            )\n    }\n}\n");
    o
}

fn kt_sum(d: &mut Decls, name: &str, vs: &BTreeMap<String, BTreeMap<String, Ty>>, about: &str) -> String {
    let names: Vec<String> = vs.keys().map(|v| format!("`{v}`")).collect();
    let mut o = format!(
        "/** {about}: a sum, one of {} as its `t` says. */\npublic sealed class {name} {{\n    /** As the runtime's value: the variant's fields and its name under `t`. */\n    public abstract fun toValue(): Value\n",
        names.join(", ")
    );
    for (v, fs) in vs {
        let cls = pascal(v);
        o.push_str(&format!("\n    /** The variant `{v}`. */\n"));
        let tag = format!("\"t\" to Value.VText({})", lit(v));
        if fs.is_empty() {
            o.push_str(&format!(
                "    public data object {cls} : {name}() {{\n        override fun toValue(): Value = Value.record({tag})\n    }}\n"
            ));
            continue;
        }
        let params: Vec<String> = fs
            .iter()
            .map(|(f, t)| format!("public val {}: {}", kt_name(f), kt_ty(d, &format!("{name}{cls}{}", pascal(f)), t)))
            .collect();
        let mut enc = vec![tag];
        for (f, t) in fs {
            enc.push(format!(
                "{} to {}",
                lit(f),
                kt_enc(d, &format!("{name}{cls}{}", pascal(f)), t, &kt_name(f), 0)
            ));
        }
        o.push_str(&format!(
            "    public data class {cls}({}) : {name}() {{\n        override fun toValue(): Value =\n            Value.record({})\n    }}\n",
            params.join(", "),
            enc.join(", ")
        ));
    }
    o.push_str(&format!(
        "\n    public companion object {{\n        /** From the runtime's value, by the variant its `t` names. */\n        public fun of(v: Value): {name} =\n            when (val t = v.field(\"t\").asText()) {{\n"
    ));
    for (v, fs) in vs {
        let cls = pascal(v);
        if fs.is_empty() {
            o.push_str(&format!("                {} -> {cls}\n", lit(v)));
        } else {
            let args: Vec<String> = fs
                .iter()
                .map(|(f, t)| kt_dec(d, &format!("{name}{cls}{}", pascal(f)), t, &format!("v.field({})", lit(f)), 0))
                .collect();
            o.push_str(&format!("                {} -> {cls}({})\n", lit(v), args.join(", ")));
        }
    }
    o.push_str(&format!(
        "                else -> throw IllegalArgumentException(\"{name}: no variant $t\")\n            }}\n    }}\n}}\n"
    ));
    o
}

// The Kotlin type of `t`, printing a record or a sum written in place under `hint`.
fn kt_ty(d: &mut Decls, hint: &str, t: &Ty) -> String {
    match t {
        Ty::Bool => "Boolean".into(),
        Ty::Int => "Long".into(),
        Ty::Text | Ty::Enum(_) => "String".into(),
        Ty::Bytes => "ByteArray".into(),
        Ty::Id(_) => "Id".into(),
        Ty::Option(x) => format!("{}?", kt_ty(d, hint, x)),
        Ty::List(x) | Ty::NonEmpty(x) => format!("List<{}>", kt_ty(d, hint, x)),
        Ty::PerDevice(x) => format!("Map<String, {}>", kt_ty(d, hint, x)),
        Ty::Ephemeral(x) => kt_ty(d, hint, x),
        Ty::Named(_) => match declared(&d.types.clone(), t) {
            Ty::Named(n) => pascal(n),
            other => kt_ty(d, hint, &other.clone()),
        },
        Ty::Struct(_) | Ty::Sum(_) => d.inline(hint, t, written_in_place()),
    }
}

// An expression reading `e`, a runtime value, as `t`.
fn kt_dec(d: &mut Decls, hint: &str, t: &Ty, e: &str, k: usize) -> String {
    match t {
        Ty::Bool => format!("{e}.asBool()"),
        Ty::Int => format!("{e}.asInt()"),
        Ty::Text | Ty::Enum(_) => format!("{e}.asText()"),
        Ty::Bytes => format!("{e}.asBytes()"),
        Ty::Id(_) => format!("{e}.asId()"),
        Ty::Option(x) => format!(
            "{e}.let {{ o{k} -> if (o{k}.isNull()) null else {} }}",
            kt_dec(d, hint, x, &format!("o{k}"), k + 1)
        ),
        Ty::List(x) | Ty::NonEmpty(x) => format!("{e}.asList().map {{ x{k} -> {} }}", kt_dec(d, hint, x, &format!("x{k}"), k + 1)),
        Ty::PerDevice(x) => format!(
            "{e}.asStruct().fields.mapValues {{ (_, x{k}) -> {} }}",
            kt_dec(d, hint, x, &format!("x{k}"), k + 1)
        ),
        Ty::Ephemeral(x) => kt_dec(d, hint, x, e, k),
        Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => match declared(&d.types.clone(), t) {
            Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => format!("{}.of({e})", kt_ty(d, hint, t)),
            other => kt_dec(d, hint, &other.clone(), e, k),
        },
    }
}

// An expression writing `e`, a value of `t`, as a runtime value.
fn kt_enc(d: &mut Decls, hint: &str, t: &Ty, e: &str, k: usize) -> String {
    match t {
        Ty::Bool => format!("Value.VBool({e})"),
        Ty::Int => format!("Value.VInt({e})"),
        Ty::Text | Ty::Enum(_) => format!("Value.VText({e})"),
        Ty::Bytes => format!("Value.VBytes({e})"),
        Ty::Id(_) => format!("Value.VId({e})"),
        Ty::Option(x) => format!("({e})?.let {{ o{k} -> {} }} ?: Value.VNull", kt_enc(d, hint, x, &format!("o{k}"), k + 1)),
        Ty::List(x) | Ty::NonEmpty(x) => format!("Value.VList({e}.map {{ x{k} -> {} }})", kt_enc(d, hint, x, &format!("x{k}"), k + 1)),
        Ty::PerDevice(x) => format!(
            "Value.VStruct({e}.mapValues {{ (_, x{k}) -> {} }})",
            kt_enc(d, hint, x, &format!("x{k}"), k + 1)
        ),
        Ty::Ephemeral(x) => kt_enc(d, hint, x, e, k),
        Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => match declared(&d.types.clone(), t) {
            Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => {
                kt_ty(d, hint, t);
                format!("{e}.toValue()")
            }
            other => kt_enc(d, hint, &other.clone(), e, k),
        },
    }
}

