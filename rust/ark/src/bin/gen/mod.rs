fn sw_record(d: &mut Decls, name: &str, fs: &BTreeMap<String, Ty>, about: &str) -> String {
    let mut o = format!("/// {about}: a record.\npublic struct {name}: Equatable {{\n");
    let mut params = vec![];
    for (f, t) in fs {
        if matches!(t, Ty::Ephemeral(_)) {
            o.push_str("    /// Ephemeral: each device writes its own slot, never ordered, never kept.\n");
        }
        let ty = sw_ty(d, &format!("{name}{}", pascal(f)), t);
        o.push_str(&format!("    public var {}: {ty}\n", sw_name(f)));
        params.push(format!("{}: {ty}", sw_bare(f)));
    }
    o.push_str(&format!("\n    public init({}) {{\n", params.join(", ")));
    for f in fs.keys() {
        o.push_str(&format!("        self.{} = {}\n", sw_bare(f), sw_name(f)));
    }
    o.push_str("    }\n\n    /// From the runtime's value.\n    public init(_ v: Value) throws {\n");
    for (f, t) in fs {
        o.push_str(&format!(
            "        {} = {}\n",
            sw_name(f),
            sw_dec(
                d,
                &format!("{name}{}", pascal(f)),
                t,
                &format!("genField(v, {})", lit(f).replace("\\$", "$"))
            )
        ));
    }
    o.push_str("    }\n\n    /// As the runtime's value.\n    public var value: Value {\n        .record(Record([");
    let pairs: Vec<String> = fs
        .iter()
        .map(|(f, t)| {
            format!(
                "({}, {})",
                lit(f).replace("\\$", "$"),
                sw_enc(d, &format!("{name}{}", pascal(f)), t, &sw_name(f))
            )
        })
        .collect();
    o.push_str(&pairs.join(", "));
    o.push_str("]))\n    }\n}\n");
    o
}

fn sw_sum(d: &mut Decls, name: &str, vs: &BTreeMap<String, BTreeMap<String, Ty>>, about: &str) -> String {
    let names: Vec<String> = vs.keys().map(|v| format!("`{v}`")).collect();
    let mut o = format!(
        "/// {about}: a sum, one of {} as its `t` says.\npublic enum {name}: Equatable {{\n",
        names.join(", ")
    );
    for (v, fs) in vs {
        o.push_str(&format!("    /// The variant `{v}`.\n"));
        if fs.is_empty() {
            o.push_str(&format!("    case {}\n", sw_name(v)));
        } else {
            let ps: Vec<String> = fs
                .iter()
                .map(|(f, t)| format!("{}: {}", sw_bare(f), sw_ty(d, &format!("{name}{}{}", pascal(v), pascal(f)), t)))
                .collect();
            o.push_str(&format!("    case {}({})\n", sw_name(v), ps.join(", ")));
        }
    }
    o.push_str("\n    /// From the runtime's value, by the variant its `t` names.\n    public init(_ v: Value) throws {\n        switch try genText(genField(v, \"t\")) {\n");
    for (v, fs) in vs {
        let tag = lit(v).replace("\\$", "$");
        if fs.is_empty() {
            o.push_str(&format!("        case {tag}: self = .{}\n", sw_bare(v)));
        } else {
            let args: Vec<String> = fs
                .iter()
                .map(|(f, t)| {
                    format!(
                        "{}: {}",
                        sw_bare(f),
                        sw_dec(
                            d,
                            &format!("{name}{}{}", pascal(v), pascal(f)),
                            t,
                            &format!("genField(v, {})", lit(f).replace("\\$", "$"))
                        )
                    )
                })
                .collect();
            o.push_str(&format!("        case {tag}: self = .{}({})\n", sw_bare(v), args.join(", ")));
        }
    }
    o.push_str(&format!(
        "        case let t: throw GeneratedTypeError(what: \"{name}: no variant \\(t)\")\n        }}\n    }}\n\n    /// As the runtime's value: the variant's fields and its name under `t`.\n    public var value: Value {{\n        switch self {{\n"
    ));
    for (v, fs) in vs {
        let tag = lit(v).replace("\\$", "$");
        if fs.is_empty() {
            o.push_str(&format!(
                "        case .{}: return .record(Record([(\"t\", .text({tag}))]))\n",
                sw_bare(v)
            ));
        } else {
            let binds: Vec<String> = fs.keys().map(|f| format!("let {}", sw_name(f))).collect();
            let mut pairs = vec![format!("(\"t\", .text({tag}))")];
            for (f, t) in fs {
                pairs.push(format!(
                    "({}, {})",
                    lit(f).replace("\\$", "$"),
                    sw_enc(d, &format!("{name}{}{}", pascal(v), pascal(f)), t, &sw_name(f))
                ));
            }
            o.push_str(&format!(
                "        case .{}({}): return .record(Record([{}]))\n",
                sw_bare(v),
                binds.join(", "),
                pairs.join(", ")
            ));
        }
    }
    o.push_str("        }\n    }\n}\n");
    o
}

// The Swift type of `t`, printing a record or a sum written in place under `hint`.
fn sw_ty(d: &mut Decls, hint: &str, t: &Ty) -> String {
    match t {
        Ty::Bool => "Bool".into(),
        Ty::Int => "Int64".into(),
        Ty::Text | Ty::Enum(_) => "String".into(),
        Ty::Bytes => "[UInt8]".into(),
        Ty::Id(_) => "Id".into(),
        Ty::Option(x) => format!("{}?", sw_ty(d, hint, x)),
        Ty::List(x) | Ty::NonEmpty(x) => format!("[{}]", sw_ty(d, hint, x)),
        Ty::PerDevice(x) => format!("[String: {}]", sw_ty(d, hint, x)),
        Ty::Ephemeral(x) => sw_ty(d, hint, x),
        Ty::Named(_) => match declared(&d.types.clone(), t) {
            Ty::Named(n) => pascal(n),
            other => sw_ty(d, hint, &other.clone()),
        },
        Ty::Struct(_) | Ty::Sum(_) => d.inline(hint, t, written_in_place()),
    }
}

// An expression reading `e`, a runtime value, as `t`; each throws, under one `try`.
fn sw_dec(d: &mut Decls, hint: &str, t: &Ty, e: &str) -> String {
    match t {
        Ty::Bool => format!("try genBool({e})"),
        Ty::Int => format!("try genInt({e})"),
        Ty::Text | Ty::Enum(_) => format!("try genText({e})"),
        Ty::Bytes => format!("try genBytes({e})"),
        Ty::Id(_) => format!("try genId({e})"),
        Ty::Option(x) => format!("try genOption({e}) {{ {} }}", sw_dec(d, hint, x, "$0")),
        Ty::List(x) | Ty::NonEmpty(x) => format!("try genList({e}) {{ {} }}", sw_dec(d, hint, x, "$0")),
        Ty::PerDevice(x) => format!("try genSlots({e}) {{ {} }}", sw_dec(d, hint, x, "$0")),
        Ty::Ephemeral(x) => sw_dec(d, hint, x, e),
        Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => match declared(&d.types.clone(), t) {
            Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => format!("try {}({e})", sw_ty(d, hint, t)),
            other => sw_dec(d, hint, &other.clone(), e),
        },
    }
}

// An expression writing `e`, a value of `t`, as a runtime value.
fn sw_enc(d: &mut Decls, hint: &str, t: &Ty, e: &str) -> String {
    match t {
        Ty::Bool => format!(".bool({e})"),
        Ty::Int => format!(".int({e})"),
        Ty::Text | Ty::Enum(_) => format!(".text({e})"),
        Ty::Bytes => format!(".bytes({e})"),
        Ty::Id(_) => format!(".id({e})"),
        Ty::Option(x) => format!("{e}.map {{ {} }} ?? .null", sw_enc(d, hint, x, "$0")),
        Ty::List(x) | Ty::NonEmpty(x) => format!(".list({e}.map {{ {} }})", sw_enc(d, hint, x, "$0")),
        Ty::PerDevice(x) => format!(".record(Record({e}.map {{ ($0.key, {}) }}))", sw_enc(d, hint, x, "$0.value")),
        Ty::Ephemeral(x) => sw_enc(d, hint, x, e),
        Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => match declared(&d.types.clone(), t) {
            Ty::Named(_) | Ty::Struct(_) | Ty::Sum(_) => {
                sw_ty(d, hint, t);
                format!("{e}.value")
            }
            other => sw_enc(d, hint, &other.clone(), e),
        },
    }
}
