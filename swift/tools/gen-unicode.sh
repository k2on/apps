#!/usr/bin/env bash
# Writes Sources/ArkDB/UnicodeTables.swift from rust/ark/src/unicode_tables.rs,
# which gen-unicode writes from the Unicode Character Database: the two
# runtimes read one copy and none is written by hand. Each table becomes one
# string of hex tokens parsed once, at first use — a literal of thousands of
# integers is what Swift's type checker is slowest at.
#
#   tools/gen-unicode.sh [RUST_TABLES] [OUT]
#
# The derivation and tools/swift.sh run it before every build; the output is
# gitignored. Moving the Unicode version is regenerating the Rust file.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="${1:-$HERE/../../rust/ark/src/unicode_tables.rs}"
OUT="${2:-$HERE/../Sources/ArkDB/UnicodeTables.swift}"
version="$(sed -n 's/^pub const UNICODE_VERSION: &str = "\([^"]*\)";$/\1/p' "$SRC")"
[ -n "$version" ] || { echo "gen-unicode.sh: $SRC has no UNICODE_VERSION" >&2; exit 1; }
table() {
  # The pairs of `static NAME: [(u32, u32); N] = [ … ];`, as "lo,hi," tokens,
  # sixteen to a line, checked against N.
  awk -v name="$1" '
    $0 ~ "^static " name ": \\[\\(u32, u32\\); [0-9]+\\] = \\[" { n = $0; sub(/.*; /, "", n); sub(/\].*/, "", n); on = 1; next }
    on && /^\];/ { on = 0; exit }
    on { while (match($0, /\(0x[0-9A-Fa-f]+, 0x[0-9A-Fa-f]+\)/)) {
           p = substr($0, RSTART + 1, RLENGTH - 2); $0 = substr($0, RSTART + RLENGTH)
           split(p, xy, ", "); toks[++k] = substr(xy[1], 3) "," substr(xy[2], 3) "," } }
    END {
      if (k != n + 0) { printf "gen-unicode.sh: %s has %d pairs, says %s\n", name, k, n > "/dev/stderr"; exit 1 }
      for (i = 1; i <= k; i++) {
        if ((i - 1) % 8 == 0) printf "%s        ", (i > 1 ? "\n" : "")
        printf "%s", toks[i]
      }
      printf "\n"
    }' "$SRC"
}
{
  cat <<HEAD
// GENERATED by swift/tools/gen-unicode.sh from rust/ark/src/unicode_tables.rs,
// which gen-unicode writes from the Unicode $version Character Database. Do not edit.

/// §5 Unicode character properties, pinned to UCD $version (\`rust/ark/src/unicode_tables.rs\`).
public enum UnicodeTables {
    /// The Unicode version every table here was generated from.
    public static let version = "$version"

    /// Property \`White_Space\` (PropList.txt).
    public static func isWhiteSpace(_ cp: UInt32) -> Bool { inRanges(whiteSpace, cp) }

    /// \`Alphabetic\`, or a general category of \`Nd\`, \`Nl\` or \`No\`: Rust's \`char::is_alphanumeric\`, pinned.
    public static func isAlphanumeric(_ cp: UInt32) -> Bool { inRanges(alphanumeric, cp) }

    /// The simple lowercase mapping (UnicodeData.txt field 13); identity where there is none.
    public static func toLowerSimple(_ cp: UInt32) -> UInt32 {
        let i = floorIndex(lower, cp)
        return i >= 0 && lower[2 * i] == cp ? lower[2 * i + 1] : cp
    }

    private static func inRanges(_ table: [UInt32], _ n: UInt32) -> Bool {
        let i = floorIndex(table, n)
        return i >= 0 && n <= table[2 * i + 1]
    }

    // The index of the last pair whose first component is at most \`n\`, or -1.
    private static func floorIndex(_ table: [UInt32], _ n: UInt32) -> Int {
        var lo = 0
        var hi = table.count / 2 - 1
        if hi < 0 || table[0] > n { return -1 }
        while lo < hi {
            let m = (lo + hi + 1) / 2
            if table[2 * m] <= n { lo = m } else { hi = m - 1 }
        }
        return lo
    }

    private static func parse(_ s: String) -> [UInt32] {
        s.split(whereSeparator: { \$0 == "," || \$0 == "\\n" || \$0 == " " }).map { UInt32(\$0, radix: 16)! }
    }

HEAD
  Q='"""'
  printf '    private static let whiteSpace: [UInt32] = parse(\n        %s\n' "$Q"; table WHITE_SPACE; printf '        %s)\n\n' "$Q"
  printf '    private static let alphanumeric: [UInt32] = parse(\n        %s\n' "$Q"; table ALPHANUMERIC; printf '        %s)\n\n' "$Q"
  printf '    private static let lower: [UInt32] = parse(\n        %s\n' "$Q"; table LOWER; printf '        %s)\n' "$Q"
  printf '}\n'
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
