#!/usr/bin/env python3
# What each app opts into of the device modules (ui/docs/app.md, The Device).
#
#   modules.py write [ROOT]   each app's <app>/ios/modules.yml, under ROOT (the repository's root by default)
#   modules.py files          the files it writes, one a line
#   modules.py check          what is committed is what it writes, and every app builds with what it lists
#
# An app lists its modules in <app>/modules.toml (`modules = ["haptics", …]`).
# Each module says in modules/<name>/module.toml its crate and what it asks
# of each platform: Info.plist keys on the iPhone and the Mac, permissions
# on Android. From those:
#
# - Xcode: <app>/ios/modules.yml, an XcodeGen file the app's project.yml
#   includes, whose template `ArkModules` (the app's target uses it) adds
#   each listed module's swift/ to the sources and its Info.plist keys to
#   the target's (the app's own keys win: a template's are overridden).
# - Gradle: the app's build.gradle.kts reads modules.toml itself and adds
#   each listed module's kotlin/ to the sources; Android's permissions are
#   checked here to be in the app's manifest (Gradle cannot merge a plain
#   source directory's), never written.
# - Cargo: the app's ffi crate depends on each listed module's crate and on
#   no other module's; checked here.
import glob
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "Generated by ui/modules.py from {app}/modules.toml: never edit; nix run .#update-modules."


def root_of(path):
    return os.path.dirname(HERE) if path is None else path


def load(root, path):
    with open(os.path.join(root, path), "rb") as f:
        return tomllib.load(f)


def apps(root):
    return sorted(os.path.dirname(os.path.relpath(p, root)) for p in glob.glob(os.path.join(root, "*", "modules.toml")))


def listed(root, app):
    return load(root, f"{app}/modules.toml").get("modules", [])


def module(root, name):
    return load(root, f"modules/{name}/module.toml")


def yaml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(yaml_value(x) for x in v) + "]"
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def xcode(root, app):
    out = [f"# {HEADER.format(app=app)}", "targetTemplates:", "  ArkModules:", "    sources:"]
    info = {}
    names = listed(root, app)
    for name in names:
        if os.path.isdir(os.path.join(root, "modules", name, "swift")):
            # No groups for the directories it climbs through: laid out in
            # them, XcodeGen put the app's other sources from outside (its
            # bindings) under the wrong ones, where Xcode then looked for
            # them (money/apps/money/ffi, money/ffi/ffi).
            out.append(f"      - path: ../../modules/{name}/swift")
            out.append("        createIntermediateGroups: false")
        info.update(module(root, name).get("ios", {}).get("info", {}))
    if not any(l.startswith("      - path") for l in out):
        out[-1] = "    sources: []"
    if info:
        out += ["    info:", "      properties:"]
        out += [f"        {k}: {yaml_value(v)}" for k, v in sorted(info.items())]
    return "\n".join(out) + "\n"


def files(root):
    return {f"{app}/ios/modules.yml": xcode(root, app) for app in apps(root)}


def check(root):
    problems = []
    for path, text in files(root).items():
        try:
            if open(os.path.join(root, path)).read() != text:
                problems.append(f"{path} is not what modules.toml makes: nix run .#update-modules")
        except FileNotFoundError:
            problems.append(f"{path} is missing: nix run .#update-modules")
    every = {os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(root, "modules", "*", "module.toml"))}
    crates = {module(root, n)["crate"]: n for n in every}
    for app in apps(root):
        names = listed(root, app)
        for n in names:
            if n not in every:
                problems.append(f"{app}/modules.toml lists {n}, which is no module (modules/{n}/module.toml)")
        names = [n for n in names if n in every]
        ffi = os.path.join(root, app, "ffi", "Cargo.toml")
        if os.path.exists(ffi):
            deps = load(root, f"{app}/ffi/Cargo.toml").get("dependencies", {})
            for n in names:
                if module(root, n)["crate"] not in deps:
                    problems.append(f"{app}/ffi/Cargo.toml has no dependency on {module(root, n)['crate']}, which modules.toml lists")
            for c, n in crates.items():
                if c in deps and n not in names:
                    problems.append(f"{app}/ffi/Cargo.toml depends on {c}, which modules.toml does not list")
        manifest = os.path.join(root, app, "android", "app", "src", "main", "AndroidManifest.xml")
        if os.path.exists(manifest):
            have = set(re.findall(r'uses-permission[^>]*android:name="([^"]+)"', open(manifest).read()))
            for n in names:
                for p in module(root, n).get("android", {}).get("permissions", []):
                    if p not in have:
                        problems.append(f"{app}'s AndroidManifest.xml lacks {p}, which {n} needs (modules/{n}/README.md)")
    for p in problems:
        print(p, file=sys.stderr)
    return not problems


def main(args):
    match args:
        case ["write", *rest] if len(rest) <= 1:
            root = root_of(rest[0] if rest else None)
            for path, text in files(root_of(None)).items():
                full = os.path.join(root, path)
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, "w") as f:
                    f.write(text)
                print(f"wrote {path}")
        case ["files"]:
            print("\n".join(files(root_of(None))))
        case ["check"]:
            sys.exit(0 if check(root_of(None)) else 1)
        case _:
            sys.exit("modules.py write [ROOT] | files | check")


if __name__ == "__main__":
    main(sys.argv[1:])
