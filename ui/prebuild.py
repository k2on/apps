def load(path):
    with open(path, "rb") as f:
        return tomllib.load(f)


def apps(root):
    return sorted(os.path.dirname(os.path.relpath(p, root)) for p in glob.glob(os.path.join(root, "*", "app.toml")))


def app_of(root, app):
    a = load(os.path.join(root, app, "app.toml"))
    a["dir"] = app
    return a


def module(root, name):
    return load(os.path.join(root, "modules", name, "module.toml"))


def modules_of(root, a):
    return [(n, module(root, n)) for n in a.get("modules", [])]


def has(a, platform):
    return platform in a.get("platforms", [])


def apple_targets(a):
    return [p for p in ("iphone", "ipad", "mac") if has(a, p)]


