def check(root):
    """Every app's app.toml says what it must, every module it lists is
    one, every Rust crate of the app depends on each listed module's crate
    it calls through, and no app's native code is committed where the
    generated projects go."""
    problems = []
    every = {os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(root, "modules", "*", "module.toml"))}
    # Each module's operations are what its module.toml's [ops] says: an
    # `impl Op for <name>` in its crate, its Output the type listed.
    declared = {p["name"] for p in cargo_metadata(root)["packages"] if ((p.get("metadata") or {}).get("ark") or {}).get("module")}
    for n in sorted(every):
        m = module(root, n)
        if m.get("crate") not in declared:
            problems.append(f"modules/{n}/Cargo.toml says no [package.metadata.ark] module, so no app can take it on")
        ops = m.get("ops", {})
        if not ops:
            problems.append(f"modules/{n}/module.toml lists no [ops]")
        # The operations are the module's port, in its crate or (a port
        # an app's update asks through) the runtime's, ark-module's
        # `src/<port>.rs`: `ark-haptics`'s is `ark_module::haptics`.
        port = n.removeprefix("ark-").replace("-", "_")
        srcs = [os.path.join(root, "modules", n, "src", "lib.rs"), os.path.join(root, "ui", "rust", "module", "src", f"{port}.rs")]
        text = "".join(open(src).read() for src in srcs if os.path.exists(src))
        for op, output in ops.items():
            found = re.search(r"impl Op for " + re.escape(op) + r" \{\s*type Module = [^;]+;\s*type Output = ([^;]+);", text)
            if not found:
                problems.append(f"modules/{n}/module.toml lists the op {op}, which neither modules/{n}/src/lib.rs nor ark-module's port implements")
            elif found.group(1).strip() != output:
                problems.append(f"modules/{n}: {op}'s Output is {found.group(1).strip()}, module.toml says {output}")
        for op in re.findall(r"impl Op for (\w+)", text):
            if op not in ops:
                problems.append(f"modules/{n}'s port implements the op {op}, which its module.toml's [ops] does not list")
    for app in apps(root):
        a = app_of(root, app)
        for k in ("name", "id", "accent", "platforms"):
            if k not in a:
                problems.append(f"{app}/app.toml says no `{k}`")
        if a.get("accent") not in theme.load()["accent"]:
            problems.append(f"{app}/app.toml's accent {a.get('accent')} is no [accent.*] of ui/theme.toml")
        # An app's modules are its crate's dependencies, and nowhere else.
        if "modules" in a:
            problems.append(f"{app}/app.toml lists modules: an app takes a module on by depending on its crate (ui/docs/app.md, How an App Opts In)")
        # Each screen and further view says its #[view] and the names it is
        # written under: the views' generator's main is made of them.
        if a.get("crate"):
            for n, sc in a.get("screens", {}).items():
                for k in ("view", "swift-view", "kotlin-view"):
                    if k not in sc:
                        problems.append(f"{app}/app.toml's screen {n} says no `{k}`")
            for n, v in a.get("views", {}).items():
                if v.get("screen") not in a.get("screens", {}):
                    problems.append(f"{app}/app.toml's view {n} is over no screen of [screens]")
                if ("view" in v) == ("commands" in v):
                    problems.append(f"{app}/app.toml's view {n} says one of `view` and `commands`")
        # The phones' library is written from `[ffi]` and `[screens]`
        # (`ffi_lib`), its crates named by their libs' names with dashes.
        if a.get("crate") and "ffi" in a:
            for k in ("host", "app", "route", "native", "domain"):
                if k not in a["ffi"]:
                    problems.append(f"{app}/app.toml's [ffi] says no `{k}`")
            for n, sc in a.get("screens", {}).items():
                if "app" not in sc:
                    problems.append(f"{app}/app.toml's screen {n} says no `app`, the type it runs in {a['crate']}")
            if all(k in a["ffi"] for k in ("route", "native", "domain")) and all("app" in sc for sc in a.get("screens", {}).values()):
                # A twin is named as its type in Kotlin and Swift: never as
                # one UniFFI's Kotlin already imports (JNA's `Native`).
                for k in ("route", "native"):
                    if a["ffi"][k].rsplit("::", 1)[-1] in ("Native", "Pointer", "Structure", "Library"):
                        problems.append(f"{app}/app.toml's [ffi] {k} is named as a JNA class its Kotlin imports")
                names = {p["name"] for p in cargo_metadata(root)["packages"]}
                for c in ffi_crates(a):
                    if c not in names:
                        problems.append(f"{app}/app.toml's [ffi] names {c.replace('-', '_')}, whose package is no {c} of the workspace")
        bg = background(a)
        for k, v in bg.items():
            if k not in BACKGROUND:
                problems.append(f"{app}/app.toml's [background] says `{k}`, which is none of {', '.join(BACKGROUND)}")
            elif not isinstance(v, BACKGROUND[k]):
                problems.append(f"{app}/app.toml's [background] `{k}` is a {BACKGROUND[k].__name__}")
        if bg.get("sync") and (sync_seconds(bg["sync"]) or 0) < 900:
            problems.append(f"{app}/app.toml's [background] sync is \"30m\" or \"2h\", at least 15m")
        needs = {"sync": "ark-background", "boot": "ark-background", "push": "ark-notifications"}
        for k, n in needs.items():
            if bg.get(k) and n not in module_names(root, a):
                problems.append(f"{app}/app.toml's [background] {k} needs its crate to depend on {n}")
        if bg.get("service-extension") and not bg.get("push"):
            problems.append(f"{app}/app.toml's [background] service-extension needs push")
        if apple_targets(a) and "apple" not in a:
            problems.append(f"{app}/app.toml has Apple platforms and no [apple]")
        if has(a, "android") and "android" not in a:
            problems.append(f"{app}/app.toml has android and no [android]")
        # An app on Android is in the F-Droid repository: its listing is [store]'s.
        if has(a, "android"):
            for k in STORE_KEYS:
                if k not in a.get("store", {}):
                    problems.append(f"{app}/app.toml's [store] says no `{k}`")
        # A device the phone hands the process (module.toml's `[phone]`) is
        # registered through ark-ffi, by its feature of the module's name,
        # which the app's generated library turns on (nix/ark-app.nix).
        ffi = load(os.path.join(root, "rust", "ark-ffi", "Cargo.toml"))
        for n in module_names(root, a) if a.get("crate") else []:
            feature = n.removeprefix("ark-")
            if "phone" in module(root, n) and (module(root, n)["crate"] not in ffi.get("dependencies", {}) or feature not in ffi.get("features", {})):
                problems.append(f"rust/ark-ffi/Cargo.toml has no feature {feature} over {module(root, n)['crate']}, whose [phone] it registers")
        # In a checkout (not nix's copy, which has no git): nothing committed
        # where the generated projects and library are.
        if shutil.which("git") and os.path.exists(os.path.join(root, ".git")):
            for d in ("ios", "android", "ffi", NATIVE):
                committed = subprocess.run(["git", "-C", root, "ls-files", f"{app}/{d}"], capture_output=True, text=True).stdout.strip()
                if committed:
                    problems.append(f"{app}/{d} is committed: an Ark app's native projects and phones' library are generated (ui/prebuild.py, nix/ark-app.nix)")
    problems += selftest(root)
    for p in problems:
        print(p, file=sys.stderr)
    return not problems


# What only `[background]` writes: none of it in an app that declares none.
BACKGROUND_MARKS = ["ArkSyncJob", "ArkBootReceiver", "ArkPushReceiver", "BOOT_COMPLETED", "BIND_JOB_SERVICE",
                    "fetch", "remote-notification", "BGTaskSchedulerPermittedIdentifiers", "aps-environment",
                    "application-groups", "app-extension", "usernotifications",
                    # The app library's hookup (ui/swift's ArkApp, ui/kotlin/app).
                    "ArkAppDelegate", "backgroundHooks", "PhoneBackground", "PhoneNotifications", "ArkNotices"]


def projects_text(root, a):
    """Everything the generator writes that says what runs in the background."""
    bundle = f"{BUNDLE_PREFIX}.{a['id']}"
    out = ""
    if apple_targets(a):
        out += json.dumps(apple_info(root, a, bundle)) + json.dumps(apple_entitlements(root, a)) + apple_project(root, a, BUNDLE_PREFIX)
    if has(a, "android"):
        out += android_manifest(root, a)
    if ark_entry(a):
        out += (swift_main(root, a) + (swift_background(root, a) or "") if apple_targets(a) else "")
        out += (kotlin_app(root, a) if has(a, "android") else "")
    return out


def selftest(root):
    """Off by default: every app that declares no `[background]` has none
    of it in its projects, and a fixture that declares all of it has each."""
    problems = []
    for app in apps(root):
        a = app_of(root, app)
        if background(a):
            continue
        text = projects_text(root, a)
        for mark in BACKGROUND_MARKS:
            if re.search(r"\b" + re.escape(mark) + r"\b", text):
                problems.append(f"{app} declares no [background], and its projects say {mark}")
    fixture = background_fixture(root)
    text = projects_text(root, fixture)
    for mark in BACKGROUND_MARKS:
        if mark not in text:
            problems.append(f"a fixture declaring every [background] has no {mark} in its projects")
    return problems


def background_fixture(root):
    """money's app.toml declaring every `[background]` key: what the
    self-test holds the projects to, and what `fixture` writes for the app
    library's build to compile."""
    fixture = app_of(root, "money")
    fixture["modules"] = module_names(root, fixture) + ["ark-notifications", "ark-background"]
    fixture["background"] = {"sync": "30m", "push": True, "boot": True, "service-extension": True}
    return fixture


def write_fixture(root, kotlin=None, swift=None):
    """The fixture's background hookup, for the app library's builds to
    compile: its Application (Kotlin), its hooks (Swift)."""
    fixture = background_fixture(root)
    if kotlin:
        write_file(os.path.join(kotlin, "ArkApp.kt"), kotlin_app(root, fixture))
    if swift:
        write_file(os.path.join(swift, "ArkBackground.swift"), swift_background(root, fixture))


def main(argv):
    p = argparse.ArgumentParser(prog="prebuild.py")
    sub = p.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write")
    w.add_argument("app")
    w.add_argument("--views")
    w.add_argument("--icon-png")
    w.add_argument("--bundle-prefix", default=BUNDLE_PREFIX)
    w.add_argument("--root", default=REPO)
    w.add_argument("--out")
    f = sub.add_parser("files")
    f.add_argument("app")
    sub.add_parser("check")
    sub.add_parser("apps")
    md = sub.add_parser("modules")
    md.add_argument("app")
    fx = sub.add_parser("fixture")
    fx.add_argument("--kotlin")
    fx.add_argument("--swift")
    vm = sub.add_parser("views")
    vm.add_argument("app")
    vm.add_argument("--root", default=REPO)
    vm.add_argument("--out")
    vm.add_argument("--written")
    ff = sub.add_parser("ffi")
    ff.add_argument("app")
    ff.add_argument("--root", default=REPO)
    ff.add_argument("--out", help="the directory its lib.rs and Cargo.toml are written in (the app's .ffi)")
    fd = sub.add_parser("fdroid")
    fd.add_argument("app")
    fd.add_argument("--root", default=REPO)
    fd.add_argument("--out")
    args = p.parse_args(argv)
    if args.cmd == "write":
        for d in write(args.root, args.app, args.views, args.icon_png, args.bundle_prefix, args.out):
            print(f"wrote {os.path.relpath(d, args.root)}")
    elif args.cmd == "files":
        a = app_of(REPO, args.app)
        print("\n".join(x for x in (("ios/project.yml" if apple_targets(a) else None), ("android/app/build.gradle.kts" if has(a, "android") else None)) if x))
    elif args.cmd == "check":
        sys.exit(0 if check(REPO) else 1)
    elif args.cmd == "fixture":
        write_fixture(REPO, args.kotlin, args.swift)
    elif args.cmd == "apps":
        print("\n".join(apps(REPO)))
    elif args.cmd == "modules":
        print("\n".join(module_names(REPO, app_of(REPO, args.app))))
    elif args.cmd == "views" and args.written:
        missing = [f for g in generated_views(app_of(args.root, args.app)) for f in (g["swift"] + ".swift", g["kotlin"] + ".kt")
                   if not os.path.exists(os.path.join(args.written, f))]
        for f in missing:
            print(f"{args.written}: no {f}, which app.toml's views name", file=sys.stderr)
        sys.exit(1 if missing else 0)
    elif args.cmd == "views":
        text = views_main(app_of(args.root, args.app))
        if args.out:
            write_file(args.out, text)
        else:
            sys.stdout.write(text)
    elif args.cmd == "ffi":
        a = app_of(args.root, args.app)
        out = args.out or os.path.join(args.root, args.app, ".ffi")
        write_file(os.path.join(out, "lib.rs"), ffi_lib(a))
        write_file(os.path.join(out, "Cargo.toml"), ffi_cargo(args.root, a))
    elif args.cmd == "fdroid":
        text = fdroid_yml(app_of(args.root, args.app))
        if args.out:
            write_file(args.out, text)
        else:
            sys.stdout.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
