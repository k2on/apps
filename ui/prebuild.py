def sync_seconds(text):
    m = re.fullmatch(r"(\d+)(m|h)", str(text).strip())
    return int(m.group(1)) * (60 if m.group(2) == "m" else 3600) if m else None


def apple_info(root, a, bundle):
    """The Info.plist's keys: the app's own, its modules' (the app's win),
    and what every Ark app has."""
    product = a["apple"]["product"]
    info = {
        "CFBundleDisplayName": a["name"],
        "CFBundleShortVersionString": "$(MARKETING_VERSION)",
        "CFBundleVersion": "$(CURRENT_PROJECT_VERSION)",
        "LSApplicationCategoryType": a["apple"].get("category", "public.app-category.utilities"),
        "UILaunchScreen": {},
        "UISupportedInterfaceOrientations": ["UIInterfaceOrientationPortrait"],
        # ProMotion: without it an app's own animation (a spring, a drag's
        # settle) is held to 60 Hz on an iPhone that draws at 120.
        "CADisableMinimumFrameDurationOnPhone": True,
        # A server at home often speaks plain http:// and ws://; the person
        # typed its address.
        "NSAppTransportSecurity": {"NSAllowsArbitraryLoads": True, "NSAllowsLocalNetworking": True},
    }
    if has(a, "ipad"):
        # Every orientation, and Split View and Slide Over (no
        # UIRequiresFullScreen): the parts adapt by size class.
        info["UISupportedInterfaceOrientations~ipad"] = [
            "UIInterfaceOrientationPortrait", "UIInterfaceOrientationPortraitUpsideDown",
            "UIInterfaceOrientationLandscapeLeft", "UIInterfaceOrientationLandscapeRight"]
    if a.get("scheme"):
        # Where the server's sign-in sends its code back to, and a route
        # opened by a link.
        info["CFBundleURLTypes"] = [{"CFBundleURLName": f"{bundle}.auth", "CFBundleURLSchemes": [a["scheme"]]}]
    modes = []
    for _, m in modules_of(root, a):
        ios = m.get("ios", {})
        for k, v in ios.get("info", {}).items():
            info.setdefault(k, v)
        modes += [x for x in ios.get("background-modes", []) if x not in modes]
    info.update(a["apple"].get("info", {}))
    bg = background(a)
    if bg.get("sync"):
        modes.append("fetch")
        info["BGTaskSchedulerPermittedIdentifiers"] = ["$(PRODUCT_BUNDLE_IDENTIFIER).sync"]
    if bg.get("push"):
        modes.append("remote-notification")
    if modes:
        info["UIBackgroundModes"] = modes
    del product
    return info


def apple_entitlements(root, a):
    out = {}
    for _, m in modules_of(root, a):
        out.update(m.get("ios", {}).get("entitlements", {}))
    out.update(a["apple"].get("entitlements", {}))
    bg = background(a)
    if bg.get("push"):
        # The development environment's; an App Store export makes it production's.
        out["aps-environment"] = "development"
    if bg.get("service-extension"):
        out["com.apple.security.application-groups"] = ["group.$(PRODUCT_BUNDLE_IDENTIFIER)"]
    return out


def plist(d):
    def v(x, pad):
        if isinstance(x, bool):
            return f"{pad}<{'true' if x else 'false'}/>"
        if isinstance(x, str):
            return f"{pad}<string>{x}</string>"
        if isinstance(x, list):
            return f"{pad}<array>\n" + "\n".join(v(y, pad + "\t") for y in x) + f"\n{pad}</array>"
        if isinstance(x, dict):
            return f"{pad}<dict>\n" + "\n".join(f"{pad}\t<key>{k}</key>\n{v(y, pad + chr(9))}" for k, y in x.items()) + f"\n{pad}</dict>"
        return f"{pad}<integer>{x}</integer>"

    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
            '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n' + v(d, "") + "\n</plist>\n")


def apple_project(root, a, prefix):
    app = a["dir"]
    product = a["apple"]["product"]
    bundle = f"{prefix}.{a['id']}"
    framework = f"{product}FFI"
    native = f"{TO_APP}/native/ios"
    sources = [{"path": f"{native}/{product}"}, {"path": "Generated"}, {"path": "Resources"},
               # Groups of their own, not laid out in the directories they
               # climb through: laid out in them, XcodeGen put the bindings
               # under the wrong groups, where Xcode then looked for them.
               {"path": "../ffi/ios/swift", "createIntermediateGroups": False}]
    if ark_entry(a):
        # The app library (ui/swift's ArkApp): compiled over the app's own
        # bindings, so as the app's sources here, and a module of its own
        # under nix, linked prebuilt.
        sources.append({"path": f"{TO_REPO}/ui/swift/Sources/ArkApp", "createIntermediateGroups": False})
    for name, _ in modules_of(root, a):
        if os.path.isdir(os.path.join(root, "modules", name, "swift")):
            sources.append({"path": f"{TO_REPO}/modules/{name}/swift", "createIntermediateGroups": False})
    local = os.path.join(root, app, "modules")
    for d in sorted(glob.glob(os.path.join(local, "*", "swift"))):
        sources.append({"path": f"{TO_APP}/modules/{os.path.basename(os.path.dirname(d))}/swift", "createIntermediateGroups": False})
    destinations = (["iOS"] if {"iphone", "ipad"} & set(apple_targets(a)) else []) + (["macOS"] if has(a, "mac") else [])
    family = ",".join(x for x, p in (("1", "iphone"), ("2", "ipad")) if has(a, p))
    entitlements = apple_entitlements(root, a)
    target = {
        "type": "application",
        "platform": "auto",
        "supportedDestinations": destinations,
        "sources": sources,
        "dependencies": [
            {"package": "ArkUI", "product": "ArkUI"},
            {"framework": f"../ffi/ios/{framework}.xcframework", "embed": False},
            # What the Rust standard library and its random numbers reach for.
            {"sdk": "Security.framework"},
            {"sdk": "SystemConfiguration.framework"},
        ],
        "info": {"path": "Resources/Info.plist", "properties": apple_info(root, a, bundle)},
        "settings": {"base": {
            "PRODUCT_BUNDLE_IDENTIFIER": bundle,
            "TARGETED_DEVICE_FAMILY": family or "1",
            "GENERATE_INFOPLIST_FILE": False,
            "ASSETCATALOG_COMPILER_APPICON_NAME": "AppIcon",
            "ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME": "AccentColor",
        }},
    }
    if entitlements:
        target["entitlements"] = {"path": "Resources/App.entitlements", "properties": entitlements}
    targets = {product: target}
    if background(a).get("service-extension"):
        # The Notification Service Extension, a process of its own by
        # Apple's design (modules/ark-notifications/README.md): its own
        # target, embedded in the iPhone's app, sharing an App Group.
        notices = f"{product}Notices"
        targets[notices] = {
            "type": "app-extension",
            "platform": "iOS",
            "sources": [{"path": f"{TO_REPO}/modules/ark-notifications/swift-extension", "createIntermediateGroups": False}],
            "info": {"path": "Resources/Notices-Info.plist", "properties": {
                "CFBundleDisplayName": a["name"],
                "CFBundleShortVersionString": "$(MARKETING_VERSION)",
                "CFBundleVersion": "$(CURRENT_PROJECT_VERSION)",
                "NSExtension": {"NSExtensionPointIdentifier": "com.apple.usernotifications.service",
                                "NSExtensionPrincipalClass": "$(PRODUCT_MODULE_NAME).NotificationService"}}},
            "entitlements": {"path": "Resources/Notices.entitlements",
                             "properties": {"com.apple.security.application-groups": [f"group.{bundle}"]}},
            "settings": {"base": {"PRODUCT_BUNDLE_IDENTIFIER": f"{bundle}.notices", "GENERATE_INFOPLIST_FILE": False}},
        }
        target["dependencies"].append({"target": notices, "embed": True, "platformFilter": "ios"})
    tests = os.path.join(root, app, "native", "ios", f"{product}Tests")
    if os.path.isdir(tests):
        targets[f"{product}Tests"] = {
            "type": "bundle.unit-test",
            "platform": "iOS",
            "sources": [{"path": f"{native}/{product}Tests"}],
            "dependencies": [{"target": product}],
            "settings": {"base": {"PRODUCT_BUNDLE_IDENTIFIER": f"{bundle}.tests", "GENERATE_INFOPLIST_FILE": True}},
        }
    project = {
        "name": product,
        "options": {
            "bundleIdPrefix": prefix,
            "deploymentTarget": {"iOS": a["apple"].get("deployment", "26.0"), "macOS": a["apple"].get("deployment", "26.0")},
            "createIntermediateGroups": True,
        },
        "settings": {"base": {
            "MARKETING_VERSION": a.get("version", "1.0"),
            "CURRENT_PROJECT_VERSION": "1",
            "CODE_SIGN_STYLE": "Automatic",
            # Swift 5 language mode, not 6: the bridge's typed half declares
            # `Id.none` a static of a type that is not `Sendable`, and the
            # kernel calls back on its own threads, which the app meets with
            # a queue rather than actors.
            "SWIFT_VERSION": "5.0",
            "SWIFT_STRICT_CONCURRENCY": "minimal",
        }},
        # ArkUI for SwiftUI, every Ark app's (ui/swift).
        "packages": {"ArkUI": {"path": f"{TO_REPO}/ui/swift"}},
        "targets": targets,
        "schemes": {product: {
            "build": {"targets": {product: "all"} | ({f"{product}Tests": ["test"]} if len(targets) > 1 else {})},
            **({"test": {"targets": [f"{product}Tests"]}} if len(targets) > 1 else {}),
            "archive": {"config": "Release"},
        }},
    }
    return f"# {HEADER.format(app=app)}" + yaml(project) + "\n"


def asset_catalog(a, out, icon_png):
    t = theme.load()
    accent = t["accent"][a["accent"]]
    files = {
        "Contents.json": json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
        "AccentColor.colorset/Contents.json": theme.colorset(accent),
        "AppIcon.appiconset/Contents.json": json.dumps({
            "images": [{"filename": "icon-1024.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"},
                       {"filename": "icon-1024.png", "idiom": "mac", "scale": "1x", "size": "512x512"}],
            "info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
    }
    # The mark alone, as the app draws it (a first run's page, `app`): a
    # vector template the page tints, Android's drawable/mark.
    svg = os.path.join(REPO, a["dir"], a.get("icon", {}).get("svg", "icon.svg"))
    if os.path.exists(svg):
        viewport, _, shapes = svg_shapes(svg)
        files["Mark.imageset/Contents.json"] = json.dumps({
            "images": [{"filename": "mark.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"}}, indent=2) + "\n"
        files["Mark.imageset/mark.svg"] = mark_svg(*mark_of(viewport, shapes))
    for p, text in files.items():
        write_file(os.path.join(out, p), text)
    if icon_png:
        shutil.copyfile(icon_png, os.path.join(out, "AppIcon.appiconset", "icon-1024.png"))


def mark_svg(viewport, shapes):
    """icon.svg's mark alone as an SVG, every shape black: a template an
    asset catalog tints."""
    w, h = viewport
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{num(w)}" height="{num(h)}" viewBox="0 0 {num(w)} {num(h)}">']
    for d, _, transforms, opacity in shapes:
        t = " ".join(transforms)
        o = f' fill-opacity="{opacity}"' if opacity else ""
        path = f'<path d="{d}" fill="#000000"{o}/>'
        out.append(f'<g transform="{t}">{path}</g>' if t else path)
    out.append("</svg>")
    return "\n".join(out) + "\n"


