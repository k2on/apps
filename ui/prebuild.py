def fdroid_yml(a):
    """F-Droid's metadata for an app, from its app.toml's `[store]`: what
    nix/fdroid.nix lays beside its APK in the repository."""
    st = a["store"]
    out = ["Categories:"] + [f"  - {c}" for c in st["categories"]]
    out += [
        f"License: {st['license']}",
        f"WebSite: {st['website']}",
        f"SourceCode: {st['source']}",
        f"IssueTracker: {st['issues']}",
        "",
        f"Name: {a['name']}",
        f"Summary: {st['summary']}",
        "Description: |-",
    ]
    for i, para in enumerate(st["description"].strip().split("\n\n")):
        if i:
            out.append("")
        out += ["    " + line for line in para.strip().splitlines()]
    out += ["", "AutoUpdateMode: None", "UpdateCheckMode: None", ""]
    return "\n".join(out)


STORE_KEYS = ("summary", "description", "categories", "license", "website", "source", "issues")


def check(root):
    """Every app's app.toml says what it must, every module it lists is
    one, every Rust crate of the app depends on each listed module's crate
    it calls through, and no app's native code is committed where the
    generated projects go."""
    problems = []
    every = {os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(root, "modules", "*", "module.toml"))}
    # Each module's operations are what its module.toml's [ops] says: an
    # `impl Op for <name>` in its crate, its Output the type listed.
    for n in sorted(every):
        m = module(root, n)
        ops = m.get("ops", {})
        if not ops:
            problems.append(f"modules/{n}/module.toml lists no [ops]")
        # The operations are the module's port, in its crate or (a port
        # an app's update asks through) the runtime's, ark-module's
        # `src/<port>.rs`: `ark-haptics`'s is `ark_module::haptics`.
        port = n.removeprefix("ark-").replace("-", "_")
        srcs = [os.path.join(root, "modules", n, "src", "lib.rs"), os.path.join(root, "ui", "rust", "module", "src", f"{port}.rs")]
        text = "".join(open(src).read() for src in srcs if os.path.exists(src))
        for op, output in ops.items():
            found = re.search(r"impl Op for " + re.escape(op) + r" \{\s*type Module = [^;]+;\s*type Output = ([^;]+);", text)
            if not found:
                problems.append(f"modules/{n}/module.toml lists the op {op}, which neither modules/{n}/src/lib.rs nor ark-module's port implements")
            elif found.group(1).strip() != output:
                problems.append(f"modules/{n}: {op}'s Output is {found.group(1).strip()}, module.toml says {output}")
        for op in re.findall(r"impl Op for (\w+)", text):
            if op not in ops:
                problems.append(f"modules/{n}'s port implements the op {op}, which its module.toml's [ops] does not list")
        # A module's Android resources are compiled into every app that
        # lists it, beside the generated ones and the other modules': each
        # is named for the module (ark-dpc's `xml/ark_dpc_admin.xml`).
        prefix = n.replace("-", "_") + "_"
        for f in sorted(glob.glob(os.path.join(root, "modules", n, "res", "*", "*"))):
            if not os.path.basename(f).startswith(prefix):
                problems.append(f"modules/{n}/res/{os.path.relpath(f, os.path.join(root, 'modules', n, 'res'))} is not named {prefix}…: a module's resources are named for it")
        for r in m.get("android", {}).get("receivers", []):
            if "name" not in r:
                problems.append(f"modules/{n}/module.toml has a receiver with no name")
            for d in r.get("meta-data", []):
                res = re.fullmatch(r"@(\w+)/(\w+)", d.get("resource", ""))
                if res and not glob.glob(os.path.join(root, "modules", n, "res", f"{res.group(1)}*", f"{res.group(2)}.*")):
                    problems.append(f"modules/{n}/module.toml's receiver {r.get('name')} names {d['resource']}, which modules/{n}/res does not have")
    for app in apps(root):
        a = app_of(root, app)
        for k in ("name", "id", "accent", "platforms"):
            if k not in a:
                problems.append(f"{app}/app.toml says no `{k}`")
        if a.get("accent") not in theme.load()["accent"]:
            problems.append(f"{app}/app.toml's accent {a.get('accent')} is no [accent.*] of ui/theme.toml")
        for n in a.get("modules", []):
            if n not in every:
                problems.append(f"{app}/app.toml lists {n}, which is no module (modules/{n}/module.toml)")
        if apple_targets(a) and "apple" not in a:
            problems.append(f"{app}/app.toml has Apple platforms and no [apple]")
        if has(a, "android") and "android" not in a:
            problems.append(f"{app}/app.toml has android and no [android]")
        # An app on Android is in the F-Droid repository: its listing is [store]'s.
        if has(a, "android"):
            for k in STORE_KEYS:
                if k not in a.get("store", {}):
                    problems.append(f"{app}/app.toml's [store] says no `{k}`")
        # The app's crate reaches a module only through its port
        # (ark_app::modules); the phones' bridge links the module's crate,
        # whose foreign trait the phones implement.
        bridge = a.get("ffi", {}).get("dir")
        crate_dir = os.path.join(root, app, bridge or "app")
        if a.get("crate") and os.path.exists(os.path.join(crate_dir, "Cargo.toml")):
            deps = load(os.path.join(crate_dir, "Cargo.toml")).get("dependencies", {})
            for n in a.get("modules", []):
                if n in every and module(root, n)["crate"] not in deps:
                    problems.append(f"{app}/{bridge or 'app'}/Cargo.toml has no dependency on {module(root, n)['crate']}, which app.toml lists")
        # In a checkout (not nix's copy, which has no git): nothing committed
        # where the generated projects and library are.
        if shutil.which("git") and os.path.exists(os.path.join(root, ".git")):
            for d in ("ios", "android", "ffi", NATIVE):
                committed = subprocess.run(["git", "-C", root, "ls-files", f"{app}/{d}"], capture_output=True, text=True).stdout.strip()
                if committed:
                    problems.append(f"{app}/{d} is committed: an Ark app's native projects and phones' library are generated (ui/prebuild.py, nix/ark-app.nix)")
    for p in problems:
        print(p, file=sys.stderr)
    return not problems


def main(argv):
    p = argparse.ArgumentParser(prog="prebuild.py")
    sub = p.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write")
    w.add_argument("app")
    w.add_argument("--views")
    w.add_argument("--icon-png")
    w.add_argument("--bundle-prefix", default=BUNDLE_PREFIX)
    w.add_argument("--root", default=REPO)
    w.add_argument("--out")
    f = sub.add_parser("files")
    f.add_argument("app")
    sub.add_parser("check")
    sub.add_parser("apps")
    fd = sub.add_parser("fdroid")
    fd.add_argument("app")
    fd.add_argument("--root", default=REPO)
    fd.add_argument("--out")
    args = p.parse_args(argv)
    if args.cmd == "write":
        for d in write(args.root, args.app, args.views, args.icon_png, args.bundle_prefix, args.out):
            print(f"wrote {os.path.relpath(d, args.root)}")
