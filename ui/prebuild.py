def write_file(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def copy_views(views, ext, to):
    if not views:
        return
    for f in sorted(glob.glob(os.path.join(views, f"*.{ext}"))):
        os.makedirs(to, exist_ok=True)
        shutil.copyfile(f, os.path.join(to, os.path.basename(f)))


def ffi_lib_name(a):
    """The phones' library: the generated UniFFI shim over the app's crate."""
    return f"{a['id']}_ffi"


def write(root, app, views=None, icon_png=None, prefix=BUNDLE_PREFIX, out=None):
    a = app_of(REPO, app)
    out = out or os.path.join(root, app, NATIVE)
    written = []
    if apple_targets(a):
        ios = os.path.join(out, "ios")
        write_file(os.path.join(ios, "project.yml"), apple_project(REPO, a, prefix))
        asset_catalog(a, os.path.join(ios, "Resources", "Assets.xcassets"), icon_png)
        if not icon_png and shutil.which("rsvg-convert"):
            png = os.path.join(ios, "Resources", "Assets.xcassets", "AppIcon.appiconset", "icon-1024.png")
            svg = os.path.join(REPO, app, a.get("icon", {}).get("svg", "icon.svg"))
            # Opaque: App Store Connect refuses an icon with alpha.
            subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", "-b", "white", "-o", png, svg], check=True)
        copy_views(views, "swift", os.path.join(ios, "Generated"))
        os.makedirs(os.path.join(ios, "Generated"), exist_ok=True)
        if ark_entry(a):
            write_file(os.path.join(ios, "Generated", "ArkApp.swift"), swift_main(REPO, a))
            if swift_background(REPO, a):
                write_file(os.path.join(ios, "Generated", "ArkBackground.swift"), swift_background(REPO, a))
        written.append(ios)
    if has(a, "android"):
        andr = os.path.join(out, "android")
        h = HEADER.format(app=app)
        write_file(os.path.join(andr, "settings.gradle.kts"), ANDROID_SETTINGS.format(header=h, app=app))
        # An Ark app's graph has the library plugin (the modules' builds); an app
        # of Kotlin alone's has only what it applies.
        library = '    id("com.android.library") version "8.7.3" apply false\n' if kernel(a) else ""
        write_file(os.path.join(andr, "build.gradle.kts"), ANDROID_ROOT.format(header=h, library=library))
        write_file(os.path.join(andr, "gradle.properties"), "org.gradle.jvmargs=-Xmx2g\nandroid.useAndroidX=true\nkotlin.code.style=official\n")
        write_file(os.path.join(andr, "app", "build.gradle.kts"), android_gradle(REPO, a, ffi_lib_name(a)))
        write_file(os.path.join(andr, "app", "src", "main", "AndroidManifest.xml"), android_manifest(REPO, a))
        android_resources(REPO, a, os.path.join(andr, "app", "src", "main", "res"))
        copy_views(views, "kt", os.path.join(andr, "generated"))
        os.makedirs(os.path.join(andr, "generated"), exist_ok=True)
        if ark_entry(a):
            write_file(os.path.join(andr, "generated", "ArkApp.kt"), kotlin_app(REPO, a))
            write_file(os.path.join(andr, "generated", "ArkActivity.kt"), kotlin_activity(REPO, a))
        written.append(andr)
    return written


