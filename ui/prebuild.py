def yaml(v, indent=0):
    """A value as YAML, enough for XcodeGen's: maps, lists, scalars."""
    pad = "  " * indent
    if isinstance(v, dict):
        if not v:
            return " {}"
        return "".join(f"\n{pad}{k}:{yaml(x, indent + 1)}" for k, x in v.items())
    if isinstance(v, list):
        if not v:
            return " []"
        if all(not isinstance(x, (dict, list)) for x in v):
            return " [" + ", ".join(scalar(x) for x in v) + "]"
        out = ""
        for x in v:
            if isinstance(x, dict):
                items = list(x.items())
                k, first = items[0]
                out += f"\n{pad}- {k}:{yaml(first, indent + 2)}"
                for k, y in items[1:]:
                    out += f"\n{pad}  {k}:{yaml(y, indent + 2)}"
            else:
                out += f"\n{pad}- {scalar(x)}"
        return out
    return " " + scalar(v)


def scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


