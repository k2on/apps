#!/usr/bin/env python3
# An Ark app's native projects, generated (ui/docs/app.md, "Generated, Not
# Committed"): nothing native of an app is committed; this writes it from
#
#   <app>/app.toml            its name, id, accent, platforms, modules, and
#                             what it asks of each platform itself
#   modules/<name>/module.toml  what each module it lists asks of each
#                             platform (Info.plist keys, entitlements,
#                             background modes; permissions, services,
#                             receivers, Maven dependencies) and its res/
#   <app>/icon.svg            its icon
#   ui/theme.toml             its accent's colours
#   the generated views       ark-ui-gen's SwiftUI and Compose of its #[view]s
#
#   prebuild.py write <app> [--views DIR] [--icon-png FILE] [--bundle-prefix P] [--root ROOT]
#   prebuild.py files <app>    what it writes, one a line
#   prebuild.py check          every app's app.toml and modules hold together
#
# It writes into <app>/.native/ (ignored by git): `ios/` (an XcodeGen
# project, one multiplatform target for the iPhone, the iPad and the Mac, its
# asset catalog and entitlements) and `android/` (a Gradle project, its
# manifest and resources), each compiling the app's hand-written native
# sources (<app>/native/, what is not written in Rust yet) and the device
# modules' swift/ and kotlin/ beside the generated views. nix builds them
# (`<app>-ios-simulator`, `<app>-macos`, `<app>-apk`) and `nix run
# .#<app>-prebuild` writes them for Xcode and Android Studio.
