def backup_excluded(root, a):
    """What the app's modules keep out of every backup and device-to-device
    transfer (their module.toml's [android] `backup-exclude`)."""
    out = []
    for _, m in modules_of(root, a):
        out += [e for e in m.get("android", {}).get("backup-exclude", []) if e not in out]
    return out


def backup_rules(head, excluded):
    """The data-extraction rules (Android 12 and later) and the full-backup
    rules (before) that leave `excluded` out."""
    lines = "".join(f'\n        <exclude domain="{e["domain"]}" path="{e["path"]}" />' for e in excluded)
    extraction = f'''<?xml version="1.0" encoding="utf-8"?>
{head}
<data-extraction-rules>
    <cloud-backup>{lines}
    </cloud-backup>
    <device-transfer>{lines}
    </device-transfer>
</data-extraction-rules>
'''
    full = "".join(f'\n    <exclude domain="{e["domain"]}" path="{e["path"]}" />' for e in excluded)
    backup = f'''<?xml version="1.0" encoding="utf-8"?>
{head}
<full-backup-content>{full}
</full-backup-content>
'''
    return {"xml/data_extraction_rules.xml": extraction, "xml/backup_rules.xml": backup}


def android_manifest(root, a):
    andr = a["android"]
    perms = list(andr.get("permissions", []))
    services = []
    receivers = []
    meta = []
    for _, m in modules_of(root, a):
        ma = m.get("android", {})
        perms += [p for p in ma.get("permissions", []) if p not in perms]
        services += ma.get("services", [])
        receivers += ma.get("receivers", [])
        meta += ma.get("meta-data", [])
    scheme = a.get("scheme")
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER.format(app=a['dir'])} -->",
             '<manifest xmlns:android="http://schemas.android.com/apk/res/android">']
    lines += [f'    <uses-permission android:name="{p}" />' for p in perms]
    for f in andr.get("features", []):
        lines.append(f'    <uses-feature android:name="{f["name"]}" android:required="{str(f.get("required", True)).lower()}" />')
    scheme = a.get("scheme")
    links = ""
    if scheme:
        hosts = "".join(f'\n                <data android:scheme="{scheme}" android:host="{h}" />' for h in andr.get("hosts", []))
        links = f'''
            <!-- Where the server's sign-in sends the code back to. -->
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />{hosts}
            </intent-filter>
            <!-- A link to a route ({scheme}://…), navigated to. -->
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="{scheme}" />
            </intent-filter>'''
    extra = ""
    for s in services:
        actions = "".join(f'\n                <action android:name="{x}" />' for x in s.get("actions", []))
        fg = f' android:foregroundServiceType="{s["foreground"]}"' if s.get("foreground") else ""
        extra += f'''
        <service android:name="{s["name"]}" android:exported="{str(s.get("exported", False)).lower()}"{fg}>
            <intent-filter>{actions}
            </intent-filter>
        </service>'''
    # A module's broadcast receivers: a device admin (ark-dpc), each with
    # the permission a sender must hold, the actions it takes and its own
    # meta-data (the admin's policies, a resource of the module's res/).
    for r in receivers:
        actions = "".join(f'\n                <action android:name="{x}" />' for x in r.get("actions", []))
        perm = f' android:permission="{r["permission"]}"' if r.get("permission") else ""
        inner = f"\n            <intent-filter>{actions}\n            </intent-filter>" if actions else ""
        inner += "".join(f'\n            <meta-data android:name="{d["name"]}" android:resource="{d["resource"]}" />' for d in r.get("meta-data", []))
        close = f"{inner}\n        </receiver>" if inner else ""
        extra += f'''
        <receiver android:name="{r["name"]}" android:exported="{str(r.get("exported", False)).lower()}"{perm}{">" if inner else " />"}{close}'''
    for d in meta:
        extra += f'\n        <meta-data android:name="{d["name"]}" android:resource="{d["resource"]}" />'
    # In the launcher, unless app.toml says `launcher = false`: an app that
    # is the phone's device owner (ark-dpc) is reached some other way, and on
    # a fully managed phone Android draws no icon for an app with none.
    launcher = '\n                <category android:name="android.intent.category.LAUNCHER" />' if andr.get("launcher", True) else ""
    theme = andr.get("theme")
    # Kept out of backups (allowBackup is false) and, on Android 12 and
    # later, out of a device-to-device transfer, which allowBackup alone
    # does not stop: what a module keeps on this device only.
    rules = ""
    if backup_excluded(root, a):
        rules = ('\n        android:dataExtractionRules="@xml/data_extraction_rules"'
                 '\n        android:fullBackupContent="@xml/backup_rules"')
    # A server at home often speaks plain http://, and the person typed its
    # address: only for an app that reaches one.
    clear = '\n        android:usesCleartextTraffic="true"' if "android.permission.INTERNET" in perms else ""
    activity = ""
    if not theme:
        activity += '\n            android:theme="@style/Theme.Ark.Starting"'
    if scheme:
        # The sign-in's return comes back to the same activity.
        activity += '\n            android:launchMode="singleTask"'
    if andr.get("config-changes"):
        activity += f'\n            android:configChanges="{"|".join(andr["config-changes"])}"'
    lines.append(f'''
    <!-- enableOnBackInvokedCallback: the back gesture is predictive (Android 14
         and later). -->
    <application
        android:label="@string/app_name"
        android:icon="@mipmap/ic_launcher"
        android:roundIcon="@mipmap/ic_launcher_round"
        android:allowBackup="false"{clear}{rules}
        android:enableOnBackInvokedCallback="true"
        android:theme="{theme or "@android:style/Theme.DeviceDefault.NoActionBar"}">
        <activity
            android:name=".MainActivity"
            android:exported="true"{activity}
            android:windowSoftInputMode="adjustResize">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />{launcher}
            </intent-filter>{links}
        </activity>{extra}
    </application>

</manifest>''')
    return "\n".join(lines) + "\n"


def android_resources(root, a, out):
    """strings, the splash's colours from the theme, the adaptive icon, the
    themed icon and the mark from icon.svg."""
    t = theme.load()
    accent = t["accent"][a["accent"]]
    ground = {s: theme.side_colors(t, s)["background"] for s in ("light", "dark")}
    head = f"<!-- {HEADER.format(app=a['dir'])} -->"
    files = {
        "values/strings.xml": f'<?xml version="1.0" encoding="utf-8"?>\n{head}\n<resources>\n    <string name="app_name">{a["name"]}</string>\n</resources>\n',
        "values/colors.xml": f'<?xml version="1.0" encoding="utf-8"?>\n{head}\n<resources>\n    <color name="splash_ground">#FF{ground["light"].lstrip("#").upper()}</color>\n    <color name="splash_mark">#FF{accent["light"]["accent"].lstrip("#").upper()}</color>\n</resources>\n',
        "values-night/colors.xml": f'<?xml version="1.0" encoding="utf-8"?>\n{head}\n<resources>\n    <color name="splash_ground">#FF{ground["dark"].lstrip("#").upper()}</color>\n    <color name="splash_mark">#FF{accent["dark"]["accent"].lstrip("#").upper()}</color>\n</resources>\n',
        # The system splash on the page's ground with the mark in the
        # accent, held until the first screen has what it draws, then the
        # theme the app draws in.
        "values/themes.xml": f'''<?xml version="1.0" encoding="utf-8"?>
{head}
<resources>
    <style name="Theme.Ark.Starting" parent="Theme.SplashScreen">
        <item name="windowSplashScreenBackground">@color/splash_ground</item>
        <item name="windowSplashScreenAnimatedIcon">@drawable/splash</item>
        <item name="postSplashScreenTheme">@android:style/Theme.DeviceDefault.NoActionBar</item>
    </style>
</resources>
''',
    }
    svg = os.path.join(root, a["dir"], a.get("icon", {}).get("svg", "icon.svg"))
    viewport, background, shapes = svg_shapes(svg)
    background = background or accent["light"]["accent"]
    # The adaptive icon's 108-unit canvas: the SVG drawn on it whole.
    files["drawable/ic_launcher_background.xml"] = vector(108, viewport, [(f"M0 0h{num(viewport[0])}v{num(viewport[1])}h-{num(viewport[0])}z", background, [], None)], comment="icon.svg's ground")
    files["drawable/ic_launcher_foreground.xml"] = vector(108, viewport, shapes, comment="icon.svg's mark; also the themed icon")
    mark_viewport, mark = mark_of(viewport, shapes)
    files["drawable/mark.xml"] = vector(24, mark_viewport, mark, comment="icon.svg's mark alone, as the app draws it (the sign-in's page)")
    files["drawable/splash.xml"] = vector(288, viewport, shapes, colour="@color/splash_mark", comment="the mark as the splash's icon, in the accent")
    adaptive = f'''<?xml version="1.0" encoding="utf-8"?>
{head}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
'''
    files["mipmap-anydpi-v26/ic_launcher.xml"] = adaptive
    files["mipmap-anydpi-v26/ic_launcher_round.xml"] = adaptive
    if a["android"].get("theme"):
        # The app draws its own first frame (its theme, its colours, in
        # native/android/res): no splash of ArkUI's.
        for k in ("values/themes.xml", "values/colors.xml", "values-night/colors.xml", "drawable/splash.xml"):
            files.pop(k)
    if backup_excluded(root, a):
        files.update(backup_rules(head, backup_excluded(root, a)))
    for p, text in files.items():
        if os.path.exists(native_dir(root, a, "res", p)):
            raise SystemExit(f"{a['dir']}/native/android/res/{p} is generated (ui/prebuild.py): leave it out")
        write_file(os.path.join(out, p), text)


