def svg_shapes(path):
    """icon.svg as (background, shapes): the full-canvas rectangle's fill,
    and every other shape as (path data, fill, transforms) in document
    order, a group's transforms outermost first. The subset icons here are
    drawn in: <rect>, <path>, <g transform>, a fill attribute."""
    tree = ET.parse(path)
    svg = tree.getroot()
    ns = "{http://www.w3.org/2000/svg}"
    vb = [float(x) for x in svg.get("viewBox", "0 0 108 108").split()]
    w, h = vb[2], vb[3]
    background = None
    shapes = []

    def walk(el, transforms, inherited):
        for c in el:
            tag = c.tag.replace(ns, "")
            t = transforms + ([c.get("transform")] if c.get("transform") else [])
            fill = c.get("fill", inherited)
            if tag == "g":
                walk(c, t, fill)
            elif tag == "rect":
                x, y = float(c.get("x", 0)), float(c.get("y", 0))
                rw, rh = float(c.get("width")), float(c.get("height"))
                nonlocal background
                if background is None and not shapes and x == 0 and y == 0 and rw == w and rh == h and fill.startswith("#"):
                    background = fill
                    continue
                rx = float(c.get("rx", 0))
                if rx:
                    d = (f"M{x + rx} {y}h{rw - 2 * rx}a{rx} {rx} 0 0 1 {rx} {rx}v{rh - 2 * rx}a{rx} {rx} 0 0 1 -{rx} {rx}"
                         f"h-{rw - 2 * rx}a{rx} {rx} 0 0 1 -{rx} -{rx}v-{rh - 2 * rx}a{rx} {rx} 0 0 1 {rx} -{rx}z")
                else:
                    d = f"M{x} {y}h{rw}v{rh}h-{rw}z"
                shapes.append((d, fill, t, c.get("fill-opacity")))
            elif tag == "path":
                shapes.append((c.get("d"), fill, t, c.get("fill-opacity")))

    walk(svg, [], "#000000")
    return (w, h), background, shapes


def vector_groups(transform):
    """An SVG transform list as VectorDrawable groups, outermost first."""
    out = []
    for name, args in re.findall(r"(\w+)\(([^)]*)\)", transform or ""):
        v = [float(x) for x in re.split(r"[ ,]+", args.strip()) if x]
        if name == "translate":
            out.append({"translateX": v[0], "translateY": v[1] if len(v) > 1 else 0})
        elif name == "scale":
            out.append({"scaleX": v[0], "scaleY": v[1] if len(v) > 1 else v[0]})
        elif name == "rotate":
            out.append({"rotation": v[0]} | ({"pivotX": v[1], "pivotY": v[2]} if len(v) == 3 else {}))
        else:
            raise SystemExit(f"icon.svg: a transform the Android icon cannot say: {name}")
    return out


def mark_of(viewport, shapes):
    """The mark alone, on a canvas of its own: when every shape is drawn
    through the same `translate(t t) scale(k)` (the glyph centred in the
    icon's safe zone), the shapes untransformed on the (W - 2t) / k canvas
    that maps to; otherwise the icon's own canvas."""
    ts = {tuple(t) for _, _, t, _ in shapes}
    if len(ts) == 1:
        groups = [g for t in next(iter(ts)) for g in vector_groups(t)]
        if len(groups) == 2 and "translateX" in groups[0] and "scaleX" in groups[1]:
            t, k = groups[0]["translateX"], groups[1]["scaleX"]
            side = (viewport[0] - 2 * t) / k
            return (side, side), [(d, f, [], o) for d, f, _, o in shapes]
    return viewport, shapes


def num(x):
    return f"{x:g}"


def vector(size, viewport, shapes, colour=None, comment=""):
    """A VectorDrawable of `shapes` on the SVG's canvas, `size` dp square;
    every fill `colour` when given (a themed icon's, the splash's)."""
    w, h = viewport
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {comment} -->" if comment else None,
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             f'    android:width="{size}dp"', f'    android:height="{size}dp"',
             f'    android:viewportWidth="{num(w)}"', f'    android:viewportHeight="{num(h)}">']
    for d, fill, transforms, opacity in shapes:
        groups = [g for t in transforms for g in vector_groups(t)]
        indent = "    "
        for g in groups:
            attrs = " ".join(f'android:{k}="{num(v)}"' for k, v in g.items())
            lines.append(f"{indent}<group {attrs}>")
            indent += "    "
        c = colour or ("#FF" + fill[1:].upper() if fill.startswith("#") and len(fill) == 7 else fill)
        alpha = f' android:fillAlpha="{opacity}"' if opacity else ""
        lines.append(f'{indent}<path android:fillColor="{c}"{alpha} android:pathData="{d}" />')
        for _ in groups:
            indent = indent[:-4]
            lines.append(f"{indent}</group>")
    lines.append("</vector>")
    return "\n".join(l for l in lines if l is not None) + "\n"


