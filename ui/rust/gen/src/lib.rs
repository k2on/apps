//! The phones' code for a view laid out once in Rust: SwiftUI ([`swift`])
//! and Compose ([`kotlin`]), written from what the view function says when
//! it is run over paths (`ark_app::view::Recorder`, `accounts::record()`).
//!
//! A recording is a [`View`] whose values are paths into the screen's
//! record (`shelf.title`), whose `for`s and `if`s are kept as such, and
//! whose messages were built from probes (`OpenAccount { id: "⟦a.id⟧" }`);
//! [`Msg`] reads a message's `Debug` back into its case and fields, and
//! each emitter writes it as the platform's UniFFI binding spells it.
//!
//! Generated files say where they came from and are never edited: `nix run
//! .#update-ui` writes them, `checks.ui` fails when they are stale.

use std::fmt::Debug;

pub use ark_app::view::{Input, Part, View};
use ark_app::view::{PROBE_CLOSE, PROBE_OPEN};

pub mod kotlin;
pub mod swift;

/// What an emitter needs to know of the screen besides its view.
#[derive(Clone, Debug)]
pub struct Screen {
    /// The generated view's name: `AccountsView` (Swift), `AccountsScreen` (Kotlin).
    pub name: &'static str,
    /// The hand-written holder of the runtime the view reads and sends to:
    /// it has `page` (the record) and `send(msg)`.
    pub holder: &'static str,
    /// The Rust file it is written from, for the header.
    pub source: &'static str,
    /// The Kotlin package.
    pub package: &'static str,
    /// The name the record is read as in the emitted code (the view
    /// function's parameter).
    pub root: &'static str,
    /// Kotlin imports the app's own pieces need.
    pub imports: &'static [&'static str],
}

/// The line every generated file starts with.
pub fn header(comment: &str, screen: &Screen) -> String {
    format!(
        "{comment} Generated by `nix run .#update-ui` from {} — do not edit.\n{comment} The layout is said once, in Rust; change it there.\n",
        screen.source
    )
}

/// A message as its `Debug` wrote it: a case and its fields.
#[derive(Clone, Debug, PartialEq)]
pub struct Msg {
    pub case: String,
    pub fields: Vec<(String, Arg)>,
}

/// A message's field.
#[derive(Clone, Debug, PartialEq)]
pub enum Arg {
    /// A path into the record (a probe), or `$0` (what an input gave).
    Path(String),
    Text(String),
    Number(String),
    Bool(bool),
    None,
}

/// What an input's message is called with, marked so it can be found.
pub const INPUT: &str = "$0";

impl Msg {
    /// `m` read back from its `Debug`.
    pub fn of(m: &impl Debug) -> Msg {
        Msg::parse(&format!("{m:?}")).unwrap_or_else(|| panic!("a message the emitters can't read: {m:?}"))
    }

    /// The message a text input makes, its text a mark.
    pub fn typed<M: Debug>(i: &Input<String, M>) -> Msg {
        Msg::of(&(i.0)(ark_app::view::Probe::probe(INPUT)))
    }

    /// The message a switch makes, the field that follows it marked.
    pub fn switched<M: Debug>(i: &Input<bool, M>) -> Msg {
        let (on, off) = (Msg::of(&(i.0)(true)), Msg::of(&(i.0)(false)));
        let mut m = on.clone();
        for (k, v) in m.fields.iter_mut() {
            if off.fields.iter().any(|(k2, v2)| k2 == k && v2 != v) {
                *v = Arg::Path(INPUT.into());
            }
        }
        m
    }

    /// The message an amount entered makes, the field that follows it marked.
    pub fn counted<M: Debug>(i: &Input<i64, M>) -> Msg {
        let (one, two) = (Msg::of(&(i.0)(1)), Msg::of(&(i.0)(2)));
        let mut m = one.clone();
        for (k, v) in m.fields.iter_mut() {
            if two.fields.iter().any(|(k2, v2)| k2 == k && v2 != v) {
                *v = Arg::Path(INPUT.into());
            }
        }
        m
    }

    fn parse(s: &str) -> Option<Msg> {
        let s = s.trim();
        let (case, rest) = match s.find([' ', '{', '(']) {
            Some(i) => (&s[..i], s[i..].trim()),
            None => (s, ""),
        };
        let mut fields = vec![];
        if let Some(body) = rest.strip_prefix('{').and_then(|r| r.strip_suffix('}')) {
            for part in split_top(body) {
                let (k, v) = part.split_once(':')?;
                fields.push((k.trim().to_string(), Arg::parse(v.trim())?));
            }
        } else if !rest.is_empty() {
            return None;
        }
        Some(Msg { case: case.into(), fields })
    }
}

impl Arg {
    fn parse(v: &str) -> Option<Arg> {
        Some(match v {
            "true" => Arg::Bool(true),
            "false" => Arg::Bool(false),
            "None" => Arg::None,
            v if v.starts_with('"') => {
                let text = unescape(v.strip_prefix('"')?.strip_suffix('"')?);
                match text.strip_prefix(PROBE_OPEN).and_then(|t| t.strip_suffix(PROBE_CLOSE)) {
                    Some(path) => Arg::Path(path.into()),
                    None => Arg::Text(text),
                }
            }
            v if v.chars().all(|c| c.is_ascii_digit() || c == '-' || c == '.') => Arg::Number(v.into()),
            _ => return None,
        })
    }
}

/// `s` split at its top-level commas.
fn split_top(s: &str) -> Vec<&str> {
    let (mut out, mut depth, mut start, mut quoted, mut escaped) = (vec![], 0, 0, false, false);
    for (i, c) in s.char_indices() {
        match c {
            _ if escaped => escaped = false,
            '\\' if quoted => escaped = true,
            '"' => quoted = !quoted,
            '{' | '(' | '[' if !quoted => depth += 1,
            '}' | ')' | ']' if !quoted => depth -= 1,
            ',' if !quoted && depth == 0 => {
                out.push(s[start..i].trim());
                start = i + 1;
            }
            _ => {}
        }
    }
    if !s[start..].trim().is_empty() {
        out.push(s[start..].trim());
    }
    out
}

fn unescape(s: &str) -> String {
    let mut out = String::new();
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => match chars.next() {
                Some('n') => out.push('\n'),
                Some(c) => out.push(c),
                None => {}
            },
            c => out.push(c),
        }
    }
    out
}

/// `net_worth` as Swift and Kotlin spell a UniFFI field: `netWorth`.
pub fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        match c {
            '_' => up = true,
            c if up => {
                out.extend(c.to_uppercase());
                up = false
            }
            c => out.push(c),
        }
    }
    out
}

/// A path into the record as the platforms spell it: `p.netWorth`.
pub fn path(p: &str) -> String {
    p.split('.').map(camel).collect::<Vec<_>>().join(".")
}

/// Text as a string literal both languages read.
pub fn quoted(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace('$', "\\$"))
}

/// A value as the platforms write it: a path into the record, or a
/// literal (`nil` and `null` are each language's none).
pub fn value(v: &str, none: &str) -> String {
    match v {
        "None" => none.into(),
        v if v.starts_with("Some(") && v.ends_with(')') => value(&v[5..v.len() - 1], none),
        v if v.starts_with('"') && v.len() >= 2 => quoted(&unescape(&v[1..v.len() - 1])),
        v if v == "true" || v == "false" || v.starts_with(|c: char| c.is_ascii_digit() || c == '-') => v.into(),
        v => path(v),
    }
}

/// A message's field as the platforms write it: `input` is what an input
/// gave (`$0`, `it`).
pub fn arg(a: &Arg, input: &str, none: &str) -> String {
    match a {
        Arg::Path(p) if p == INPUT => input.into(),
        Arg::Path(p) => path(p),
        Arg::Text(t) => quoted(t),
        Arg::Number(n) => n.clone(),
        Arg::Bool(b) => b.to_string(),
        Arg::None => none.into(),
    }
}

/// Lines written at an indent.
#[derive(Default)]
pub struct Out {
    text: String,
    indent: usize,
}

impl Out {
    pub fn line(&mut self, s: impl AsRef<str>) {
        let s = s.as_ref();
        if !s.is_empty() {
            self.text.push_str(&"    ".repeat(self.indent));
        }
        self.text.push_str(s);
        self.text.push('\n');
    }

    /// `open`, then `body` indented, then `close`.
    pub fn block(&mut self, open: impl AsRef<str>, close: &str, body: impl FnOnce(&mut Out)) {
        self.line(open);
        self.indent += 1;
        body(self);
        self.indent -= 1;
        self.line(close);
    }

    pub fn text(self) -> String {
        self.text
    }

    /// The last line's closing brace joined to what reopens it
    /// (`} else {`), `body` in it, and closed again.
    pub fn reopen(&mut self, s: &str, body: impl FnOnce(&mut Out)) {
        let trimmed = self.text.trim_end_matches('\n').len();
        self.text.truncate(trimmed - 1);
        self.text.push_str(s);
        self.text.push('\n');
        self.indent += 1;
        body(self);
        self.indent -= 1;
        self.line("}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Debug)]
    #[allow(dead_code)]
    enum M {
        Save,
        Open { id: String, n: i64 },
        Named { name: String },
        On { on: bool, id: String },
    }

    #[test]
    fn a_message_reads_back_from_its_debug() {
        assert_eq!(
            Msg::of(&M::Save),
            Msg {
                case: "Save".into(),
                fields: vec![]
            }
        );
        let m = Msg::of(&M::Open {
            id: ark_app::view::Probe::probe("a.id"),
            n: 3,
        });
        assert_eq!(
            m.fields,
            vec![("id".into(), Arg::Path("a.id".into())), ("n".into(), Arg::Number("3".into()))]
        );
        let typed = Msg::typed(&Input::new(|name| M::Named { name }));
        assert_eq!(typed.fields, vec![("name".into(), Arg::Path(INPUT.into()))]);
        let switched = Msg::switched(&Input::new(|on| M::On { on, id: "x, \"y\"".into() }));
        assert_eq!(
            switched.fields,
            vec![("on".into(), Arg::Path(INPUT.into())), ("id".into(), Arg::Text("x, \"y\"".into()))]
        );
    }

    #[test]
    fn paths_are_spelled_as_uniffi_spells_fields() {
        assert_eq!(path("p.net_worth"), "p.netWorth");
        assert_eq!(value("shelf.total", "nil"), "shelf.total");
        assert_eq!(value("\"Hi \\\"you\\\"\"", "nil"), "\"Hi \\\"you\\\"\"");
        assert_eq!(value("None", "null"), "null");
        assert_eq!(value("Some(3)", "nil"), "3");
    }
}
